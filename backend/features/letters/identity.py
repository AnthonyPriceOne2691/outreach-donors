"""Свой `Message-ID` письма и домен, на котором он стоит.

**Номер письма у платформы — не идентификатор письма.** В ответ на отправку
платформа возвращает свой номер (`X-Message-Id`, вида `W8Rx7c2bQvuh3sVUkwV8Hw`),
и он же долго служил якорем цепочки. Получатель этого номера не видит:
письмо приходит к нему с `Message-ID`, который платформа ставит сама, —
в угловых скобках и с доменом. Добивка с `In-Reply-To: W8Rx7c2bQvuh3sVUkwV8Hw`
(ни скобок, ни `@`) не ложилась в ветку ни у одного почтового клиента,
а запасная привязка ответа сравнивала токены `<…@…>` из заголовков ответа
с голым номером и не совпала бы ни разу. Поэтому идентификатор мы ставим
сами и знаем его до отправки.

**Домен — домен адреса From.** Письмо, у которого подпись, обратный адрес
и идентификатор на одном домене, выглядит как письмо этого домена; чужой
домен в идентификаторе — лишний след, по которому фильтры связывают наши
двадцать доменов между собой. Тот же домен у адреса ответа (`reply_to.py`).

**Случайная часть — 128 бит из `secrets`.** Запасная привязка ответа верит
идентификатору в `In-Reply-To`: угадываемый позволил бы подсунуть письмо
в чужой диалог — ровно то, от чего метку адреса ответа защищает подпись.
`email.utils.make_msgid` для этого не годится: его случайность — из `random`
(восстановима по подсмотренным значениям), и он кладёт в каждое письмо
время отправки и номер процесса — лишнее о нас у каждого получателя.

**Номер нашего письма — тоже в идентификаторе** (`m417`, как в метке адреса
ответа, то есть ничего нового наружу не уходит). По заголовку полученного
письма человек находит наше письмо без поиска, а уникальность держится
не на одной случайности: двух писем с одним номером в базе не бывает.
"""

from __future__ import annotations

import re
import secrets
from typing import TypeGuard

#: Байт случайности в идентификаторе: 128 бит — ни перебрать, ни совпасть.
RANDOM_BYTES = 16

#: Как выглядит идентификатор письма: `<левая часть@домен>`, без пробелов
#: и лишних скобок. Токены в заголовках ответа ищутся по той же форме
#: (`replies/mime.py`), и идентификатор другой формы там не найдётся.
_MESSAGE_ID_RE = re.compile(r"^<[^<>@\s]+@[^<>@\s]+>$")


class SenderAddressError(ValueError):
    """У адреса отправителя нет домена — ставить идентификатор не на чем."""


def sender_domain(email: str) -> str:
    """Домен адреса отправителя — тот, которым письмо подписано.

    Строчными: регистр в домене ничего не значит, а идентификатор и адрес
    ответа сравниваются как строки, и `Mail-A.example` рядом с `mail-a.example`
    выглядели бы двумя доменами.
    """
    local, at, domain = email.strip().rpartition("@")
    domain = domain.strip().rstrip(".").lower()
    if not at or not local or not domain:
        raise SenderAddressError(
            f"«{email}» — не адрес почты: у отправителя нет домена, и ни идентификатор "
            "письма, ни адрес ответа поставить не на чем. Ящик заводится командой "
            "outreach sender-add с полным адресом"
        )
    return domain


def new_message_id(number: int, *, sender_email: str) -> str:
    """Свежий `Message-ID` для письма `number` с ящика `sender_email`.

    Каждый вызов — новый идентификатор: письмо, вернувшееся в очередь после
    отказа платформы, может уйти с другого ящика, то есть с другого домена.
    """
    return f"<{secrets.token_hex(RANDOM_BYTES)}.m{number}@{sender_domain(sender_email)}>"


def is_message_id(value: str | None) -> TypeGuard[str]:
    """Годится ли строка в заголовок `Message-ID` или `In-Reply-To`."""
    return value is not None and _MESSAGE_ID_RE.match(value) is not None
