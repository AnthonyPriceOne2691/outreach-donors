"""Чем письмо уходит наружу.

Настоящего транспорта пока нет: двадцати почтовых доменов не заведено,
ключ платформы не выдан. Это не мешает написать всё остальное, но создаёт
единственный по-настоящему опасный соблазн среза — заглушку, которая
делает вид, что отправила.

Поэтому нулевой транспорт устроен так:

**Он отказывается отправлять на что угодно, кроме выдуманной зоны.**
Ровно тот же запрет, что стоит в `check_collect()` после истории с 670
юнитами, сожжёнными на выдуманных доменах песочницы: заглушка не должна
касаться боевых данных. Настоящему донору письмо «отправленное» нулевым
транспортом не уйдёт никогда, а в базе будет выглядеть отправленным —
и это худший исход из возможных.

**Он говорит о себе вслух.** Каждая отправка пишет в лог, что письмо
никуда не ушло, и возвращает номер с приставкой `null-`: по базе видно,
какие письма настоящие, а какие нет.

Боевой транспорт появится вместе с доменами. До тех пор попытка его
выбрать — отказ с перечислением того, чего не хватает, а не молчаливое
падение в заглушку.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from operator import attrgetter
from typing import Protocol, runtime_checkable

from backend.shared.demo import SUFFIX, is_demo_address

logger = logging.getLogger(__name__)


class TransportError(RuntimeError):
    """Письмо не ушло. Сообщение называет причину и что делать."""


class MaybeSentError(RuntimeError):
    """Почта не ответила, когда запрос мог уже дойти, — или приняла письмо, не назвав
    его номера: письмо, возможно, уже уходит.

    **Не `TransportError` намеренно.** Тот значит «точно не ушло», и отправка
    возвращает письмо в очередь — а здесь возврат означал бы второе письмо тому
    же человеку: кнопкой сразу или проходом добивок через час (находка
    «Продаж» 05.10.2026). Письмо остаётся «отправляется»: событие платформы
    запишет его ушедшим, если письмо дошло до неё, а нет — решит человек
    (`unknown_outcome.py`).
    """


@dataclass(frozen=True, slots=True)
class OutgoingFile:
    """Файл письма в том виде, в каком его берёт почта: имя, наш тип, байты.

    Тип — из белого списка (`outgoing_files.py`), а не названный браузером:
    транспорт кладёт его в письмо как есть и сам ничего не угадывает.
    """

    name: str
    content_type: str
    data: bytes


@dataclass(frozen=True, slots=True)
class Outgoing:
    """Одно письмо в том виде, в каком его принимает почта."""

    message_id: int
    to: str
    from_email: str
    from_name: str
    reply_to: str | None
    subject: str
    body: str
    #: Наш `Message-ID` этого письма, `<…@домен отправителя>`
    #: (`identity.new_message_id`). Записан в базу до вызова транспорта:
    #: на него ссылаются добивки и по нему находится письмо, если ответ
    #: пришёл без метки. Обязателен и у нулевого транспорта — путь один.
    internet_message_id: str
    #: `Message-ID` первого письма переписки. Добивка с ним ложится в ту же
    #: ветку у донора: для него это напоминание, а не письмо от незнакомого
    #: отправителя.
    in_reply_to: str | None = None
    #: Адрес страницы отписки этого донора — для заголовка
    #: `List-Unsubscribe`. В тексте письма его больше нет (юридический блок
    #: снят 23.09.2026). Пусто — собрать его нечем, и заголовка не будет.
    unsubscribe_url: str = ""
    #: Файлы письма. Бывают только у нашего ответа в переписке
    #: (`answers.py`); первое письмо и добивки уходят без них.
    attachments: tuple[OutgoingFile, ...] = ()


class Transport(Protocol):
    """Чем отправляем. Реализация возвращает номер письма у платформы.

    **Настоящий транспорт обязан класть `internet_message_id` в заголовок
    `Message-ID`.** Иначе платформа поставит письму свой идентификатор,
    которого мы не знаем: добивки сошлются на то, чего у донора нет,
    а ответ без метки не найдёт своего письма.

    **И обязан класть `in_reply_to` в заголовки**
    `In-Reply-To` и `References`. Без них добивка приходит донору
    отдельным письмом от незнакомого отправителя, а не напоминанием
    в начатой переписке — и читается как спам, которым по сути
    и становится.

    **И обязан класть `unsubscribe_url` в заголовки** `List-Unsubscribe`
    и `List-Unsubscribe-Post: List-Unsubscribe=One-Click` (RFC 8058).
    Крупные почты требуют их от массовых отправителей и учитывают
    в репутации: кнопка отписки в интерфейсе почты — это то, что донор
    нажмёт вместо «спам». Страница отписки эти `POST` принимает.

    **И обязан класть `attachments` вложениями** — каждый файл целиком,
    под своим именем и нашим типом, только на сохранение, а не на показ
    в тексте письма. Файл, потерянный по дороге, — ответ без прайса, о
    котором человек думает, что отправил его.
    """

    #: Как транспорт называется в логах и в журнале.
    name: str

    #: Настоящая ли отправка. По нему экран решает, что показать человеку.
    real: bool

    async def send(self, outgoing: Outgoing) -> str: ...


@runtime_checkable
class ByStage(Protocol):
    """Транспорт по этапу письма: у направления бывает своя учётка платформы
    (`config.outreach.mail_account`). Отправка берёт транспорт этапа своего
    письма (`sending.Sending`) — один проход добивок пишет и донорам, и
    рекламодателям, и продажам."""

    def for_stage(self, stage: str) -> Transport: ...


#: Чем отправлять: один транспорт на все письма или набор по этапам.
type Mail = Transport | ByStage


def of_stage(source: Mail, stage: str) -> Transport:
    """Транспорт письма этапа: набор по этапам отдаёт транспорт этапа,
    одиночный транспорт (подставной в тестах) — себя на любой этап."""
    return source.for_stage(stage) if isinstance(source, ByStage) else source


class NullTransport:
    """Транспорт, который ничего не отправляет.

    Существует ради экрана писем и проверки проводки: очередь, выбор
    отправителя, стоп-лист и журнал работают полностью, наружу не уходит
    ничего.
    """

    name = "null"
    real = False

    async def send(self, outgoing: Outgoing) -> str:
        if not is_demo_address(outgoing.to):
            raise TransportError(
                f"Нулевой транспорт не отправляет на боевой адрес ({outgoing.to}): "
                f"он ничего не шлёт, и письмо выглядело бы отправленным, не уйдя никуда. "
                f"Выдуманные адреса оканчиваются на {SUFFIX}; "
                f"для настоящей отправки нужен транспорт с почтовой платформой"
            )

        logger.warning(
            "письма: письмо №%s НЕ отправлено — транспорт нулевой (кому %s, тема «%s», %s, "
            "файлы: %s)",
            outgoing.message_id,
            outgoing.to,
            outgoing.subject,
            outgoing.internet_message_id,
            named(outgoing.attachments),
        )
        return f"null-{outgoing.message_id}"


def named(files: tuple[OutgoingFile, ...]) -> str:
    """Файлы письма именами — для строки лога; нет файлов — «нет»."""
    return ", ".join(map(attrgetter("name"), files)) or "нет"
