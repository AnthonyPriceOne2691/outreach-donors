"""Чем письмо уходит наружу.

Настоящего транспорта пока нет: двадцати почтовых доменов не заведено,
ключ платформы не выдан. Это не мешает написать всё остальное, но создаёт
единственный по-настоящему опасный соблазн среза — заглушку, которая
делает вид, что отправила.

Поэтому нулевой транспорт устроен так:

**Он отказывается отправлять на что угодно, кроме выдуманной зоны.**
Ровно тот же запрет, что стоит в `check_collect()` после истории с 670
юнитами, сожжёнными на выдуманных доменах песочницы: заглушка не должна
касаться боевых данных. Настоящему донору письмо «отправленное» нулевым
транспортом не уйдёт никогда, а в базе будет выглядеть отправленным —
и это худший исход из возможных.

**Он говорит о себе вслух.** Каждая отправка пишет в лог, что письмо
никуда не ушло, и возвращает номер с приставкой `null-`: по базе видно,
какие письма настоящие, а какие нет.

Боевой транспорт появится вместе с доменами. До тех пор попытка его
выбрать — отказ с перечислением того, чего не хватает, а не молчаливое
падение в заглушку.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Protocol

from backend.config import outreach as cfg
from backend.shared.demo import SUFFIX, is_demo_address

logger = logging.getLogger(__name__)


class TransportError(RuntimeError):
    """Письмо не ушло. Сообщение называет причину и что делать."""


@dataclass(frozen=True, slots=True)
class Outgoing:
    """Одно письмо в том виде, в каком его принимает почта."""

    message_id: int
    to: str
    from_email: str
    from_name: str
    reply_to: str | None
    subject: str
    body: str
    #: Идентификатор первого письма переписки у почты. Добивка с ним
    #: ложится в ту же ветку у донора: для него это напоминание,
    #: а не письмо от незнакомого отправителя.
    in_reply_to: str | None = None
    #: Адрес страницы отписки этого донора — тот же, что в тексте письма.
    #: Едет отдельным полем, потому что в заголовках он нужен целой
    #: ссылкой, а в тексте стоит внутри предложения. Пусто — собрать его
    #: нечем, и до настоящей отправки такое письмо не дойдёт: проверка
    #: юридического блока откажет раньше.
    unsubscribe_url: str = ""


class Transport(Protocol):
    """Чем отправляем. Реализация возвращает номер письма у платформы.

    **Настоящий транспорт обязан класть `in_reply_to` в заголовки**
    `In-Reply-To` и `References`. Без них добивка приходит донору
    отдельным письмом от незнакомого отправителя, а не напоминанием
    в начатой переписке — и читается как спам, которым по сути
    и становится.

    **И обязан класть `unsubscribe_url` в заголовки** `List-Unsubscribe`
    и `List-Unsubscribe-Post: List-Unsubscribe=One-Click` (RFC 8058).
    Крупные почты требуют их от массовых отправителей и учитывают
    в репутации: кнопка отписки в интерфейсе почты — это то, что донор
    нажмёт вместо «спам». Страница отписки эти `POST` принимает.
    """

    #: Как транспорт называется в логах и в журнале.
    name: str

    #: Настоящая ли отправка. По нему экран решает, что показать человеку.
    real: bool

    async def send(self, outgoing: Outgoing) -> str: ...


class NullTransport:
    """Транспорт, который ничего не отправляет.

    Существует ради экрана писем и проверки проводки: очередь, выбор
    отправителя, стоп-лист и журнал работают полностью, наружу не уходит
    ничего.
    """

    name = "null"
    real = False

    async def send(self, outgoing: Outgoing) -> str:
        if not is_demo_address(outgoing.to):
            raise TransportError(
                f"Нулевой транспорт не отправляет на боевой адрес ({outgoing.to}): "
                f"он ничего не шлёт, и письмо выглядело бы отправленным, не уйдя никуда. "
                f"Выдуманные адреса оканчиваются на {SUFFIX}; "
                f"для настоящей отправки нужен транспорт с почтовой платформой"
            )

        logger.warning(
            "письма: письмо №%s НЕ отправлено — транспорт нулевой (кому %s, тема «%s»)",
            outgoing.message_id,
            outgoing.to,
            outgoing.subject,
        )
        return f"null-{outgoing.message_id}"


def build_transport(name: str | None = None) -> Transport:
    """Транспорт по настройке. Неизвестное имя — отказ, а не заглушка."""
    chosen = (name or cfg.TRANSPORT).strip().lower()

    if chosen == "null":
        return NullTransport()

    if chosen == "sendgrid":
        raise TransportError(
            "Транспорт sendgrid ещё не написан: он ждёт двадцати почтовых доменов "
            "с настроенными SPF, DKIM и DMARC и ключа платформы. "
            "До тех пор OUTREACH_TRANSPORT=null — письма собираются, но не уходят"
        )

    raise TransportError(
        f"Транспорт «{chosen}» неизвестен. Бывают: null (ничего не шлёт), sendgrid"
    )
