"""Сверка текста с настройками «Отправителя»: стоит ли в нём подпись или физический адрес.

Подпись и адрес дописывает сборка (`letter.signed`), поэтому в шаблоне цепочки (`chain_text.unsigned`)
и в готовом письме выше блока настроек (`letter.problem`) их быть не должно — одно правило у шаблона
и у письма.

**Отдельным словом, а не вхождением строки.** Знаки, которые продолжают слово вокруг подписи, —
буква и цифра, а ещё части адреса, домена и ссылки (`@`, `/`, `:`, `-`, `_`); точка — только
внутри (`mira.example`): в конце фразы она слово закрывает. 19.11.2026: короткая подпись (имя)
вхождением строки находилась в домене сайта и адресе лида (`{{site}}` в тексте письма) — сборка
отклоняла его письмо «подпись повторяется» на каждом проходе, и первое письмо лиду не уходило.
"""

from __future__ import annotations

import re

_BEFORE = r"(?<![\w@/:.\-])"
_AFTER = r"(?![\w@/:\-])(?!\.\w)"


def squashed(text: str) -> str:
    """Текст без различий в пробелах и регистре — для сверки с настройками отправителя."""
    return " ".join(text.split()).casefold()


def mentions(text: str, value: str) -> bool:
    """Стоит ли `value` в `text` отдельным словом или фразой — без различий в пробелах и
    регистре. Внутри слова, домена, адреса или ссылки — нет: «mira» в «mirastroy.example» или
    «mira@…» — не подпись «Mira». Пустое значение не стоит нигде."""
    needle = squashed(value)
    if not needle:
        return False
    return re.search(f"{_BEFORE}{re.escape(needle)}{_AFTER}", squashed(text)) is not None
