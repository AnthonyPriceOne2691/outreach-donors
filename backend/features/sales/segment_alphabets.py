"""Алфавиты языков для сверки языка сайта с языком писем (`segment_language`) — данные, а не
правила под язык.

Язык — код ISO 639-1, имя по-русски (и после «на» — у экранов продаж, `chain_text.in_language`),
письменность, буквы алфавита и то, как сайт называет свою версию на нём (переключатель). Рядом —
письменности, которые сами называют язык, письменности словами и язык писем лиду по письменности
сайта. Правила, которые этими данными пользуются, — в `segment_language`.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Language:
    """Язык: код ISO 639-1, имя по-русски, письменность и буквы, как сайт называет его версию."""

    code: str
    name: str
    #: Письменность — первое слово имени буквы в Юникоде (`segment_language.script_of`).
    script: str
    #: Буквы алфавита строчными; пусто — алфавита в таблице нет (иероглифы, хангыль, деванагари):
    #: язык называет только письменность одного языка (`SCRIPT_NAMES`).
    letters: str
    #: Как переключатель версий называет язык: код, сокращение, самоназвание, имя по-английски и
    #: по-русски. Код из двух латинских букв — только заглавными («RU», «Ru»): строчные «de», «en» —
    #: предлоги других языков, «ru» — зона адреса в тексте.
    switch: tuple[str, ...]
    #: Ещё письменности языка: японский пишет и каной, и иероглифами.
    also: tuple[str, ...] = ()
    #: Отличительные буквы — язык называется буквами, только если они есть в тексте
    #: (`segment_language._named`). Пусто — все его буквы вне общего ядра письменности (`_core`
    #: там же). Задаются, где алфавит — чужой плюс свои буквы и среди своих есть общая с третьим
    #: языком (казахская «і» — и украинская, и белорусская).
    marks: str = ""
    #: Имя после «на», где оно не прилагательное: «на иврите», «на хинди». Пусто — имя-прилагательное,
    #: и падеж — правилом (`after_na`).
    prepositional: str = ""

    @property
    def after_na(self) -> str:
        """Имя после «на» (`chain_text.in_language`): прилагательное — в предложном падеже
        («английский» → «английском»), другое — словом таблицы («иврите», «хинди»)."""
        return self.prepositional or f"{self.name.removesuffix('ий')}ом"


