"""Колонка «Отправителя» продаж для наборов по языку письма: имя, должность, подпись и физический
адрес на каждом языке цепочек (`chain_text.LANGUAGES`).

Своим модулем, а не в `models.py`: тот стоит у предела длины файла, а наборы — одна забота
(`sender.py`: чтение, правка, журнал и выбор набора по языку письма).

**Колонка строки отправителя, а не своя таблица**: отправитель — одна строка, и экран пишет его
целиком одной кнопкой (`sender.save`): общие поля и наборы языков ложатся одной правкой, с одним
автором, одним временем правки и одной записью журнала. Своя таблица дала бы второе время правки —
экран называет «Правил … ·» по строке отправителя и по ней же встаёт заново после сохранения.

**Хранится только заданное**: `{"en": {"signature": "…"}}` — пустое поле набора не хранится, язык
без полей — тоже; наборов нет — колонка пуста. Пустое поле — «в письмах на этом языке общее».
"""

from __future__ import annotations

from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column


class SenderLanguagesMixin:
    """Наборы «Отправителя» по языку письма: код языка → поле → значение."""

    #: Пусто — наборов нет: письма на всех языках подписаны общим набором.
    languages: Mapped[dict[str, dict[str, str]] | None] = mapped_column(
        JSONB(none_as_null=True), nullable=True
    )
