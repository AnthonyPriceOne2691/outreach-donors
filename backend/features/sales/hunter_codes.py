"""Ответы Hunter на проверку адреса, которые не вердикт: 202 и отказ домену — правило продаж.

Разбор отказов у проверки и у поиска адресов общий (`contacts/provider.py`): сервис тот же,
маркеры те же, второй копии их таблицы нет. Тест прогона сбора 14.10 показал цену двух ответов
проверки адреса — здесь не разбор, а что с ними делает проход продаж:

- **202 — «ещё проверяет»**: Hunter не дождался почтового сервера и проверяет дальше, а такой же
  запрос, пока ответа нет, новым не считается — бесплатен. Раньше лид сразу ждал следующей
  очистки; теперь проход переспрашивает тут же (`asked`) — не больше `STILL_CHECKING_ASKS` раз,
  с короткой паузой общего `with_retries` (секунда, две; `Retry-After`, если Hunter его назвал),
  и каждый запрос — под ограничителем частоты прохода. Не дождались — как прежде: лид в прежнем
  статусе, следующая очистка спросит снова (`STILL_CHECKING`).
- **400 `blacklisted_domain`** — с доменом адреса сервис не работает: общий разбор называет его
  `ProviderDomainRefusedError`, повтор его не лечит. Раньше лид оставался `new`, и каждая
  очистка спрашивала снова; теперь очистка отклоняет лида сразу словами (`refused`), без
  повтора и без единицы расхода — вердикта нет, и месячный потолок место возвращает
  (`verify_cap.MonthCapped`). Проход идёт дальше: отказ одному домену, а не учётке.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable

import httpx

from backend.shared.net.retry import with_retries

#: Переспросов «ещё проверяет» в том же проходе — сверх первого запроса.
STILL_CHECKING_ASKS = 2
#: 202 и после переспросов — словами очистки: лид ждёт следующей.
STILL_CHECKING = (
    f"провайдер ещё проверяет адрес и после {STILL_CHECKING_ASKS} переспросов — "
    "повторим следующей очисткой"
)
#: Почему лид отклонён, когда сервис не работает с доменом его адреса (решение владельца 14.10).
REFUSED_DOMAIN = "адрес не проверить: сервис проверки не работает с этим доменом"


def still_checking(response: httpx.Response) -> bool:
    """202 — проверка у Hunter ещё идёт: переспросить стоит, это бесплатно."""
    return response.status_code == httpx.codes.ACCEPTED


async def asked(call: Callable[[], Awaitable[httpx.Response]]) -> httpx.Response:
    """Ответ Hunter; «ещё проверяет» — переспросить в том же проходе, не больше
    `STILL_CHECKING_ASKS` раз, паузой общего `with_retries`. Последний ответ — как есть: его
    разбирает проверяльщик. Временные отказы сети и частоты повторяет сам `call`."""
    return await with_retries(
        call,
        attempts=1 + STILL_CHECKING_ASKS,
        topic="продажи: адрес ещё проверяется",
        retry_when=still_checking,
    )


def refused(email: str) -> str:
    """Слова очистки лида, чей адрес сервис проверить не может: домен — в скобках."""
    return f"{REFUSED_DOMAIN} ({email.rpartition('@')[2]})"
