"""Тревога сторожа — одна на все правила: общего сторожа тишины (`silence.py`) и сторожа
почты этапов (`mail_watch.py`). Своим модулем: правила почты не тянут за собой общие.

**Этап в заголовке — словом, код — в коде тревоги** (ревью стыков R7, 7.1). Заголовок читает
человек: красной полосой над вкладками «Продаж», на «Обзоре» и в Telegram, — и «Очередь «sales»
есть» ему ничего не говорит. Слово одно на оба сторожа (`STAGE_GENITIVE`).

**Стоит ли тревога внимания — последней строкой** (слово Anthony 29.10.2026: «тревога
такая-то, повода для беспокойства нет или есть»). Поводом стала «Платформа молчит о доставке»:
вебхук работал, а одно письмо ждало сервер получателя, и исход пришёл бы сам. Каждая тревога
несёт пометку (`Concern`): «Повода для беспокойства нет — почему» — исход придёт сам,
это устройство, а не поломка; «Есть повод для беспокойства — почему: что сделать» — работа стоит
или деньги и данные под угрозой. Решает правило, которое тревогу поднимает: по сути, а где повод
зависит от числа — по числу. Тревога без пометки краснит тест
(`tests/test_alarm_concern.py`). Та же строка — у тревог, которые уходят в Telegram мимо ленты
(`marked`): через `send_alert` и через подставленный `alert` продаж.

**Род тревоги и где смотреть — тоже от правила** (слово владельца 17.11.2026: «нужно, чтобы алерты
стали адекватнее и информативнее»). Пятнадцать ящиков продаж молчали по одной причине — и пришло
пятнадцать сообщений подряд, а через десять минут ещё пятнадцать «прошло». Правило, у которого
тревог одного рода бывает много, задаёт род (`Kind`): лента говорит о тревогах рода из одного
прохода одним сообщением со списком (`alarm_feed.py`, слова — `alarm_words.py`). Экран
(`Alarm.screen`) — строка «где смотреть» в Telegram.
"""

from __future__ import annotations

from dataclasses import dataclass

from backend.features.core.domain import STAGE_GENITIVE, Stage
from backend.shared.alerts import MAX_CHARS, SOURCE

#: Сколько знаков сообщения остаётся тексту после имени сервиса: отправка ставит его первым и
#: режет сообщение по потолку Telegram (`shared/alerts.send_alert`).
ROOM = MAX_CHARS - len(f"{SOURCE}: ")


def direction(stage: Stage) -> str:
    """Направление словами заголовка: «направление продаж»."""
    return f"направление {STAGE_GENITIVE[stage]}"


def senders_screen(stage: Stage) -> str:
    """Экран ящиков и доменов направления — как его зовёт меню: «Домены рассылки продаж»."""
    return f"Домены рассылки {STAGE_GENITIVE[stage]}"


@dataclass(frozen=True, slots=True)
class Concern:
    """Стоит ли тревога внимания: есть ли повод для беспокойства, почему и что сделать.

    Собирается `cause` и `no_cause`: у повода всегда есть «что сделать», у его отсутствия — нет.
    Слова — коротко и без точки в конце: строку собирает `words`."""

    #: Есть ли повод для беспокойства.
    cause: bool
    #: Почему — коротко, словами человека, а не журнала.
    why: str
    #: Что сделать — одной фразой; пусто, когда повода нет.
    todo: str = ""

    @property
    def words(self) -> str:
        """Строка пометки — последняя в сообщении Telegram и под тревогой на экране."""
        if self.cause:
            return f"Есть повод для беспокойства — {self.why}: {self.todo}."
        return f"Повода для беспокойства нет — {self.why}."


def cause(why: str, todo: str) -> Concern:
    """Повод есть: работа стоит или деньги и данные под угрозой — почему и что сделать."""
    return Concern(cause=True, why=why, todo=todo)


def no_cause(why: str) -> Concern:
    """Повода нет: исход придёт сам, это устройство, а не поломка, — почему."""
    return Concern(cause=False, why=why)


@dataclass(frozen=True, slots=True)
class Kind:
    """Род тревоги: тревоги одного рода, сменившие состояние в одном проходе ленты, уходят одним
    сообщением со списком — «Молчат ящики продаж — 15», а не пятнадцатью. Слова — коротко и без
    точки в конце: предложение собирает лента."""

    #: Заголовок сообщения рода — он же ключ рода в ленте: «Молчат ящики продаж». Этап — словом.
    title: str
    #: Что происходит — общими словами рода, без чисел одной тревоги: их несёт её строка в списке.
    detail: str = ""


@dataclass(frozen=True, slots=True)
class Alarm:
    """Одна тревога: что молчит, с каких пор и что это значит."""

    code: str
    title: str
    detail: str
    #: Этап, о почте или обходе которого тревога: тревога продаж — только с правом «Продажи»
    #: (решение Anthony 10.10.2026, П2б), Этапа 2 — с правом «Рекламодатели». Общая — без этапа.
    stage: Stage | None = None
    #: Стоит ли тревога внимания — последней строкой в Telegram и меткой на «Обзоре». У каждой
    #: тревоги сервиса обязательна (`tests/test_alarm_concern.py`). Повод сменился у той же
    #: тревоги — лента скажет о ней ещё раз, когда он появился (`alarm_feed.Feed`).
    concern: Concern | None = None
    #: Род: тревоги одного рода из одного прохода — одно сообщение со списком. Без рода — сообщение
    #: на тревогу.
    kind: Kind | None = None
    #: Имя тревоги в списке рода — коротко и одно, пока она идёт: адрес ящика. Пусто — заголовок.
    item: str = ""
    #: Что с ней сейчас — после имени в списке «тревоги»: «писем ждут: 22». В «прошло» его нет:
    #: к концу тревоги число уже другое.
    brief: str = ""
    #: Где смотреть — экран сервиса, как его зовёт меню: «Домены рассылки продаж». Пусто — строки
    #: «где смотреть» нет.
    screen: str = ""


def marked(text: str, concern: Concern | None) -> str:
    """Текст тревоги с пометкой последней строкой; без пометки — как есть. Длинный текст режется
    перед пометкой, а не вместе с ней: отправка режет сообщение с конца по потолку Telegram."""
    if concern is None:
        return text
    line = concern.words
    room = ROOM - len(line) - 1
    body = text if len(text) <= room else f"{text[: room - 1]}…"
    return f"{body}\n{line}"
