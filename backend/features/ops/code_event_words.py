"""Слова событий входа с кодом — что сторож входов и прав говорит в Telegram (`access_watch.py`).

23.11.2026: вход с кодом из приложения выкачен, его события пишутся в журнал действий
(`access/second_step.py`, `access/code_login.py`, `access/administration.py`), а сторож о них
молчал. Код выключили, сбросили или вошли кодом восстановления — второй шаг снят или обойдён, и
узнавать об этом с экрана журнала, когда туда кто-нибудь зайдёт, поздно. Слова — те же, что у
событий доступа (`access_event_words.py`): чья учётка, что с ней, кто это сделал, минута по
Москве и где смотреть; сообщения собирает он же.

- **Выключение, сброс и вход кодом восстановления — с поводом для беспокойства** (`alarms.cause`):
  сторож не знает, хозяин ли учётки это был, и пометка говорит, что сделать, если не он. Каждая
  пометка — своим сообщением, как у новых админов: у выключения, сброса и входа кодом
  восстановления разное «что сделать». Сброс без автора записи — «кто — команда на сервере», как
  заведение учётки без автора, и пометка своя: сбросил тот, у кого есть доступ к серверу.
- **Включение — без повода** (`alarms.no_cause`) и строкой общего сообщения прохода, рядом с
  правками доступа: дело обычное, но включённый на чужой учётке код — знак, что пароль у чужого и
  хозяина запрут его же вторым шагом, и владелец должен это видеть.
- **Кодов восстановления мало (`FEW`) или ноль — прямо**: без телефона дальше не войти, и что
  сделать (`RENEW`). Порог — три: сеанс закрывается после часа без действий, и без телефона код
  уходит на каждый вход — три кода это день работы с перерывами, а новые коды выходят только с
  включением кода заново или сбросом. При пяти и больше до конца ещё далеко, и «мало» звучало бы с
  первых же входов, а при одном — хозяин узнал бы об этом в последний вход.

Паролей, кодов и набранного здесь нет: запись журнала о коде несёт только почту учётки и, у входа
кодом восстановления, сколько их осталось.
"""

from __future__ import annotations

from collections.abc import Iterable

from backend.features.core.domain import AuditAction
from backend.features.ops.access_events import CodeEvent, Happened
from backend.features.ops.alarm_words import counted
from backend.features.ops.alarms import Concern, cause, no_cause

#: Кодов восстановления «мало» — столько и меньше: без телефона это день работы с перерывами.
FEW = 3

#: Формы слов: «осталось 2 кода», «ещё 1 вход».
CODES = ("код", "кода", "кодов")
LOGINS = ("вход", "входа", "входов")

#: Пометка выключения: выключают паролем и кодом — у выключившего было и то и другое.
OFF = cause(
    "у того, кто выключил вход с кодом, были и пароль, и код",
    "если это не вы и не хозяин учётки — отключить её в разделе «Учётки» и сбросить ей пароль",
)

#: Пометка сброса админом: сброс подтверждают паролем админа — у сбросившего был и он.
RESET = cause(
    "после сброса учётку открывает один пароль",
    "если сбрасывали не вы и не по вашему слову — сбросить пароль ей и админу, который сбрасывал",
)

#: Пометка сброса командой на сервере: у сбросившего есть доступ к серверу.
RESET_ON_SERVER = cause(
    "после сброса учётку открывает один пароль, а сбросили командой на сервере",
    "если это не вы — сбросить учётке пароль и выяснить, у кого есть доступ к серверу",
)

#: Пометка входа кодом восстановления: такой код пускает без телефона.
RECOVERY = cause(
    "код восстановления пускает без телефона",
    "если входили не вы и не хозяин учётки — сбросить ей пароль и вход с кодом в разделе «Учётки»",
)

#: Пометка включения: повода нет — код учётку защищает.
ENABLED = no_cause("код из приложения защищает учётку: одного пароля к ней теперь мало")

#: Пометка по событию; сброс без автора — своя (`concern`).
CONCERNS: dict[AuditAction, Concern] = {
    AuditAction.TOTP_ENABLED: ENABLED,
    AuditAction.TOTP_DISABLED: OFF,
    AuditAction.TOTP_RESET: RESET,
    AuditAction.RECOVERY_CODE_USED: RECOVERY,
}

#: Что случилось — заголовком сообщения: одно событие — «<что> — почта», несколько — «<что> — N».
TITLES: dict[AuditAction, str] = {
    AuditAction.TOTP_ENABLED: "Включён вход с кодом",
    AuditAction.TOTP_DISABLED: "Выключен вход с кодом",
    AuditAction.TOTP_RESET: "Сброшен вход с кодом",
    AuditAction.RECOVERY_CODE_USED: "Вход кодом восстановления",
}

#: Что случилось — строкой: со строчной буквы, без автора и времени. Вход кодом восстановления —
#: со счётом оставшихся (`what`).
DONE: dict[AuditAction, str] = {
    AuditAction.TOTP_ENABLED: "вход с кодом включён",
    AuditAction.TOTP_DISABLED: "вход с кодом выключен — учётку снова открывает один пароль",
    AuditAction.TOTP_RESET: (
        "вход с кодом сброшен — ключ и коды восстановления удалены, сеансы учётки закрыты"
    ),
}

#: Что сделать, когда кодов мало или не осталось: новые выходят только с включением кода заново.
RENEW = (
    "Что сделать: новые коды выходят, когда вход с кодом включают заново, — выключить и включить "
    "его («Вход с кодом» в меню у почты); роль требует код или телефона нет — сбросить вход с "
    "кодом в разделе «Учётки», единственному админу — командой на сервере."
)


def concern(event: CodeEvent) -> Concern:
    """Пометка события: включение — без повода, остальное — с поводом; сброс без автора — свой."""
    if event.action is AuditAction.TOTP_RESET and event.author is None:
        return RESET_ON_SERVER
    return CONCERNS[event.action]


def alarming(event: CodeEvent) -> bool:
    """Своим сообщением с поводом — всё, кроме включения: оно идёт строкой общего сообщения."""
    return concern(event).cause


def what(event: CodeEvent) -> str:
    """Что случилось с входом с кодом учётки — без автора и времени, со строчной буквы."""
    if event.action is AuditAction.RECOVERY_CODE_USED:
        return _recovered(event.left)
    return DONE[event.action]


def advice(events: Iterable[Happened]) -> list[str]:
    """Строка «что сделать», если у входа кодом восстановления кодов осталось мало или ноль;
    иначе — ни одной."""
    few = any(isinstance(one, CodeEvent) and _few(one.left) for one in events)
    return [RENEW] if few else []


def _recovered(left: int | None) -> str:
    """Вход кодом восстановления и сколько их осталось; мало или ноль — прямо, что без телефона
    дальше не войти. Счёта в записи нет — без него."""
    said = "вход кодом восстановления вместо кода из приложения"
    if left is None:
        return said
    if left <= 0:
        return f"{said} — кодов больше нет: без телефона дальше не войти"
    if _few(left):
        return (
            f"{said}, осталось {counted(left, CODES)} — это мало: без телефона ещё "
            f"{counted(left, LOGINS)}, а дальше не войти"
        )
    return f"{said}, осталось {counted(left, CODES)}"


def _few(left: int | None) -> bool:
    """Кодов осталось мало или ни одного."""
    return left is not None and left <= FEW
