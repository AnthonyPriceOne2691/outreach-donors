class UnknownMarketError(ValueError):
    """Страны нет в карте рынков. Язык подставлять нельзя: английский
    по умолчанию уводит прогон в другой веб, и уводит молча."""


def serp_language(country: str) -> str:
    """Язык, с которым спрашивается выдача. Один на рынок."""
    key = country.strip().lower()
    language = SERP_LANGUAGE.get(key)
    if language is None:
        raise UnknownMarketError(
            f"Страны «{country}» нет в карте рынков — язык выдачи вывести нечем. "
            "Внести в SERP_LANGUAGE, сверившись с тем, на каком языке там ищут; "
            "английский по умолчанию увёл бы прогон в другой веб"
        )
    return language


def keygen_languages(country: str) -> tuple[str, ...]:
    """Языки, на которых собирается пул — НАЗВАНИЯМИ, не кодами.

    Первым идёт основной: он же язык выдачи, и с него начинается пул,
    если потолок делится не поровну.
    """
    key = country.strip().lower()
    codes = (serp_language(key), *EXTRA_KEYGEN_LANGUAGES.get(key, ()))
    return tuple(LANGUAGE_NAMES.get(code, code) for code in dict.fromkeys(codes))
