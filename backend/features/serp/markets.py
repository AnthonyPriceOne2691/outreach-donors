"""Рынок прогона: какой язык у выдачи и на каких языках просить ключи.

**Умолчания на английский здесь нет, и это главное решение модуля.**
Раньше страна без записи молча получала `en`: прогон по Австрии уходил
искать английскую выдачу по английским ключам и **отчитывался успехом**.
Одиннадцать стран из пятидесяти пяти жили так — все, кого забыли внести.
Теперь незнакомая страна — это отказ с именем страны, а не тихий
английский.

`en` при этом остаётся законным **ответом**, а не заглушкой: у США, ЮАР,
Ирландии и Нигерии веб действительно англоязычный, и запись им проставлена
явно. Разница между «мы знаем, что здесь английский» и «мы не знаем и
подставили английский» видна только в коде, а стоит она целого прогона.

**Язык выдачи один, языков генерации может быть несколько.** Замер
22.09.2026: один и тот же французский запрос в Канаде с `language_code=en`
и `fr` дал восемь общих доменов из девяти — Google определяет язык больше
по самому запросу. Значит решает то, **на каком языке написаны ключи**,
а код языка в запросе — поправка на полях. Поэтому выдаче уходит основной
язык рынка, а ключи собираются на всех.

**Второй язык добавляется не каждому двуязычному рынку, а только там, где
на нём есть отдельная пресса.** Список намеренно короткий: язык, который
и так покрыт основным, удваивает вызовы модели и ничего не приносит.
"""

