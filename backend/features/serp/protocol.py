"""Что сервис ждёт от источника выдачи.

**Интерфейс принимает пачку ключей, а не один.** Это не удобство, а следствие
того, как устроен основной провайдер. У DataForSEO отложенный режим —
двухфазный: задачи ставятся `task_post`, результат забирается опросом, и одна
задача выполняется минутами. По ключу за раз сотня ключей заняла бы часы;
пачкой — одно ожидание на всех. В референсе это решено так же: постановка
чанком, затем опрос раз в две секунды с потолком ожидания.

Провайдеров за интерфейсом двое не ради абстракции. Отладка не должна упираться
в чужой баланс, падение провайдера не должно останавливать прогон, а смена
тарифа не должна переписывать логику отбора.

Страна передаётся кодом ISO-2. Перевод в то, что понимает конкретный провайдер,
его забота: DataForSEO принимает числовой `location_code`, и карта соответствий
ляжет внутрь его адаптера.

**Один запрос — один ключ, правилом отсюда** (`keyword_key`, `distinct_keywords`).
Поиску не важны регистр и лишние пробелы, а провайдер берёт деньги за каждую
поставленную задачу. До 10.10.2026 смета считала строки поля, а выдача снимала
повторы только с точностью до пробелов по краям: два одинаковых ключа и вариант
с заглавными — «3 ключа» в смете, две покупки в выдаче, и за вариант с заглавными
платили второй раз (проверка прода 10.10.2026). Теперь правило одно у сметы,
запуска, обоих провайдеров и сверки «такой же прогон уже идёт».
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from typing import Protocol, runtime_checkable


def keyword_key(keyword: str) -> str:
    """Чем ключ является для выдачи: без регистра, без пробелов по краям,
    подряд идущие пробелы — одним. Пустая строка — не ключ."""
    return " ".join(keyword.split()).casefold()


def distinct_keywords(keywords: Iterable[str]) -> list[str]:
    """Ключи, за которые заплатит выдача: каждый запрос один раз — в первом
    написании, с пробелами, сведёнными к одному. Пустые строки выпадают."""
    found: dict[str, str] = {}
    for keyword in keywords:
        clean = " ".join(keyword.split())
        if clean:
            found.setdefault(clean.casefold(), clean)
    return list(found.values())


@dataclass(frozen=True, slots=True)
class SerpResult:
    """Одна позиция выдачи: адрес и то, что выдача о нём написала.

    Метрики домена берутся из Ahrefs пакетом — там они в шесть раз дешевле,
    и сюда они не приезжают.

    ⚠ Заголовок и описание здесь НЕ на всякий случай. Раньше парсер их
    выбрасывал («нас интересует только адрес»), и из-за этого судить,
    площадка перед нами или бренд, было не по чему: единственный текст,
    который сайт написал о себе, уходил в мусор на первом же шаге.
    Сниппет приходит из индекса поиска, то есть он есть даже у тех, кто
    не пустит нас на сайт, и **уже оплачен вместе с выдачей**.

    `None` означает «провайдер не дал», а не «пусто»: у источника, который
    отдаёт одни адреса, поля останутся пустыми, и судья про такой домен
    честно скажет, что смотреть было нечего.
    """

    position: int
    url: str
    title: str | None = None
    description: str | None = None


