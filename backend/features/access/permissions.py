"""Кто что может: роль плюс точечные исключения.

Проверка всегда ссылается на именованное действие, а не на роль. Разница
не косметическая: по имени роли в обработчике нельзя ответить на вопрос
«что может оператор», не прочитав все обработчики подряд, — а отвечать
на него придётся каждый раз, когда заводят нового человека.

**Отправка писем не входит в роль оператора.** Её выдают поимённо. Дело
не в недоверии к людям: скомпрометированная учётка обычного сотрудника
не должна превращаться в рассылку с наших доменов. Юниты возвращаются
первого числа, репутация домена — никогда.

**Разбор цен — отдельное действие, хотя роль оператора его включает.**
Смотреть цены может каждый (так в ТЗ), а подтверждать разобранное —
это запись в базу, ради которой вся приёмка и держится на пяти процентах
ошибок. Названо отдельно не чтобы отобрать, а чтобы на вопрос «кто
подтверждает цены» отвечал список действий, а не чтение обработчиков.

**«Продажи» закрывают этап целиком, а не пункт меню** (решение Anthony
10.10.2026, П2). Снятое право закрывает раздел «Продажи», маршруты модуля
продаж и данные этапа продаж на общих экранах: письма и переписки продаж
с их файлами, ответы лидов, черновики агента и настройки агента этапа, их
счёт в «Обзоре» и у пунктов меню. До П2 снятое право прятало только раздел:
письма продаж читались в «Письмах», переписки — в «Диалогах», пачка продаж
уходила правом `send`, агент продаж правился правом `settings`. Этап строки
проверяется здесь же (`require_stage`), а не своей копией матрицы в каждом
обработчике; действие над строкой продаж требует и своего права (`send`,
`settings`), и «Продаж». С П2б (решение Anthony 10.10.2026) — ещё записи
стоп-листа этапа продаж, ящики продаж на экране доменов, исход задач продаж,
расход операций продаж и тревоги сторожа о почте продаж.

**«Рекламодатели» закрывают Этап 2 так же, как «Продажи» — свой этап** (решение 02.11.2026;
другая сторона просила либо учётку без раздела, либо два сервиса — вышла роль).
Закрыты раздел, маршруты рекламодателей, обходов и загрузки доноров в обход, лиды файлом и всё
то же на общих экранах: письма и переписки этапа с файлами, ответы, черновики и настройки агента
этапа, счета на «Обзоре» и у пунктов меню, стоп-лист, ящики, исход задач, расход этапа, тревоги о
его почте и обходе. Какой этап каким правом открыт — `STAGE_RIGHTS`, одной строкой на этап:
`sees_stage`, `visible_stages` и `require_stage` читают её, а не знают этапы поимённо.

**Новая роль — строка, а не правка обработчиков.** Значение в `UserRole` и строка
`ROLE_PERMISSIONS` здесь, значение в `Role` и слова в `ROLE_TITLES` и `ROLE_ABOUT`
экрана (`frontend/src/api/labels.ts`) и значение в перечислении базы (`ALTER TYPE userrole ADD
VALUE`, миграцией). Забытое из этого краснит `tests/test_access_roles.py`: роль без строки матрицы молча
не могла бы ничего. Выбор роли на экране учёток и в консоли строится из этих списков.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from backend.features.core.domain import STAGE_GENITIVE, Permission, Stage, UserRole

#: Что даёт роль сама по себе.
ROLE_PERMISSIONS: dict[UserRole, frozenset[Permission]] = {
    UserRole.ADMIN: frozenset(Permission),
    # Домены рассылки оператору не положены: включённый заново домен
    # начинает разгон заново, и ошибка здесь стоит репутации домена,
    # а она не восстанавливается. Продажи — в роли: решение владельца 01.10,
    # раздел видят все. Снимается поимённо (`{"sales": false}`) и закрывает раздел,
    # маршруты модуля и данные этапа продаж на общих экранах (П2, `require_stage`);
    # закрыть всем операторам — убрать отсюда. «Рекламодатели» — так же: оператор ведёт оба этапа.
    UserRole.OPERATOR: frozenset(
        {
            Permission.VIEW,
            Permission.RUN,
            Permission.SETTINGS,
            Permission.PRICES,
            Permission.SALES,
            Permission.ADVERTISERS,
        }
    ),
    # Только Этап 1: поиск площадок, цены, письма донорам. Как оператор без продаж и рекламодателей;
    # отправка писем выдаётся поимённо, как у оператора (шапка файла).
    UserRole.DONORS: frozenset(
        {Permission.VIEW, Permission.RUN, Permission.SETTINGS, Permission.PRICES}
    ),
}

#: Этап → право, которое его открывает. Этапа здесь нет — он виден всем, кто видит базу (доноры).
STAGE_RIGHTS: dict[Stage, Permission] = {
    Stage.ADVERTISERS: Permission.ADVERTISERS,
    Stage.SALES: Permission.SALES,
}


#: Права словами — те же, что человек видит в окне прав учётки: копия `PERMISSION_TITLES`
#: из `frontend/src/api/labels.ts`, сверка построчно — `tests/test_access_words.py`. Своя
#: копия потому, что отказ сервер пишет сам, а экран его не переводит: до проверки прода
#: 10.10.2026 отказ называл код — «Действие «sales» недоступно этой учётке». «Продажи» —
#: как у `require_stage` и как у экрана после PR продаж #308 (было «раздел продаж»).
PERMISSION_TITLES: dict[Permission, str] = {
    Permission.VIEW: "смотреть базу",
    Permission.RUN: "запускать прогоны",
    Permission.SETTINGS: "править пороги",
    Permission.PRICES: "подтверждать цены",
    Permission.SEND: "отправлять письма",
    Permission.SENDERS: "домены рассылки",
    Permission.USERS: "заводить учётки",
    Permission.SALES: "Продажи",
    Permission.ADVERTISERS: "Рекламодатели",
    Permission.SPEND: "менять потолки расхода",
}


def no_right(permission: Permission) -> str:
    """Отказ «права нет» — одним местом: право словами, как в окне прав, и кто его выдаёт.

    Тесты и экраны сверяют отказ по этой функции, а не своей копией строки: слова отказа
    меняются (проверка прода 10.10.2026 — в отказе код права вместо названия), и копия
    строки в чужом тесте держала бы правку слов до его правки.
    """
    return f"Действие «{PERMISSION_TITLES[permission]}» не выдано этой учётке — права выдаёт админ"


class AccessDeniedError(PermissionError):
    """Действие запрещено. Сообщение называет право словами, а не «нет прав».

    `refusal` — машинный признак отказа рядом с текстом (заголовок ответа — `api/errors.py`):
    по нему экран перечитывает «кто я», а не по тексту, который правят.
    """

    refusal = "permission"


class OneTimePasswordError(AccessDeniedError):
    """Разовый пароль не сменён: до смены открыты только «кто я» и смена пароля (`api/deps.py`).

    Свой признак: по нему экран перечитывает «кто я» и уводит на смену пароля. До проверки
    прода 10.10.2026 открытый сеанс после сброса показывал «Доноры не загрузились · Сначала
    смените разовый пароль: POST /api/auth/password» — метод и путь вместо перехода."""

    refusal = "change-password"


class SignedOutError(AccessDeniedError):
    """Входа нет: пропуска нет, он не принят (просрочен, подделан), учётка отключена или пароль
    сменили после выдачи пропуска. Экран стирает пропуск и ведёт на вход.

    Код — 403 со своим признаком, а не 401: весь сервис за паролем прокси (Basic), и браузер
    прикладывает его к каждому запросу сам. Ответ 401 на такой запрос Chrome считает отказом
    самому паролю прокси и стирает его из памяти — следующий запрос уходит без него, и посреди
    работы всплывает окно пароля сервера (разбор продаж по исходникам Chromium, проверено в
    Chrome 11.10.2026). 401 в сервисе отвечает только прокси.
    """

    refusal = "signed-out"


@dataclass(frozen=True, slots=True)
class Actor:
    """Кто действует. Ровно то, что нужно для проверки прав, — не модель базы.

    Проверка не должна зависеть от сессии базы: так её можно звать
    откуда угодно, включая тесты без базы.
    """

    user_id: int
    role: UserRole
    is_active: bool = True
    #: Точечные исключения поверх роли: `{"send": true}` добавляет
    #: действие, `{"send": false}` отбирает.
    overrides: dict[str, Any] | None = None


def permissions_of(role: UserRole) -> frozenset[Permission]:
    return ROLE_PERMISSIONS.get(role, frozenset())


def has_permission(actor: Actor, permission: Permission) -> bool:
    """Может ли сотрудник совершить действие.

    Отключённая учётка не может ничего — проверка идёт по базе на каждом
    запросе, а не по пропуску: иначе уволенный сотрудник работает до конца
    суток, пока не истечёт выданный ему пропуск.
    """
    if not actor.is_active:
        return False

    if actor.overrides:
        override = actor.overrides.get(permission.value)
        if override is not None:
            return bool(override)

    return permission in permissions_of(actor.role)


def require(actor: Actor | None, permission: Permission) -> None:
    """Пропустить или отказать. Отказ называет право словами (`no_right`)."""
    if actor is None:
        title = PERMISSION_TITLES[permission]
        raise AccessDeniedError(f"Нужен вход: действие «{title}» требует учётки")
    if not has_permission(actor, permission):
        raise AccessDeniedError(no_right(permission))


def sees_stage(actor: Actor, stage: Stage) -> bool:
    """Видит ли сотрудник данные этапа: продажи — только с правом «Продажи» (решение
    Anthony 10.10.2026, П2), Этап 2 — с правом «Рекламодатели» (`STAGE_RIGHTS`). Доноры —
    правом самого действия, как до П2."""
    right = STAGE_RIGHTS.get(stage)
    return right is None or has_permission(actor, right)


def visible_stages(actor: Actor) -> frozenset[Stage]:
    """Этапы, которые сотрудник видит в общих списках и числах."""
    return frozenset(stage for stage in Stage if sees_stage(actor, stage))


def require_stage(actor: Actor, stage: Stage | None, what: str) -> None:
    """Пропустить к строке этапа или отказать словами: `what` — что закрыто, «Письма {stage}»;
    на место `{stage}` встаёт этап строки в родительном падеже: «Письма рекламодателей».

    `None` — у строки этапа нет (ответ без письма не на наш адрес) или строки нет вовсе:
    «не найдено» скажет тот, кто её ищет, как и без этой проверки.
    """
    if stage is not None and not sees_stage(actor, stage):
        closed, right = what.format(stage=STAGE_GENITIVE[stage]), STAGE_RIGHTS[stage]
        raise AccessDeniedError(f"{closed} — только с правом «{PERMISSION_TITLES[right]}»")
