from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime

from sqlalchemy.ext.asyncio import AsyncSession

from backend.features.core.domain import Stage
from backend.features.core.models.outreach import SenderModel
from backend.features.ops.alarms import cause, marked
from backend.features.outreach.senders import disable
from backend.shared.alerts import send_alert

#: С чего начать — у всех правил: причину паузы видно у платформы, а не в тревоге.
REVIEW = "Что делать: разобрать причину — журнал платформы, жалобы, списки блокировок"

#: Совет прежнего правила парковки (`letters/events._park_if_burning`; доноры, рекламодатели):
#: доля отказов — за всё время ящика, и включение её не меняет.
LIFETIME_ADVICE = (
    f"{REVIEW}. Доля здесь — за всё время ящика: «Включить заново» на экране «Домены "
    "рассылки» её не обнуляет, и первый же отказ, даже по старому письму, снова поставит "
    "ящик на паузу — пока новые письма без отказов не опустят долю ниже порога"
)


def window_advice(window: int) -> str:
    """Совет правила мягких сигналов (`health.py`, у продаж): пауза — по окну последних
    `window` писем ящика, включение начинает разгон заново, а окно не очищает."""
    return (
        f"{REVIEW} — и после разбора включить ящик на экране «Домены рассылки» кнопкой "
        f"«Включить заново»: разгон начнётся заново. Окно последних {window} писем ящика "
        "включение не очищает: пока в нём прежние отказы и жалобы, следующий отказ или "
        "жалоба, даже по старому письму, снова поставят ящик на паузу — новые письма "
        "вытесняют старые по одному"
    )


@dataclass(frozen=True, slots=True)
class AutoPause:
    """Ящик, вставший на паузу сам: адрес, этап, почему — с числами, и что делать — по
    правилу, которое поставило паузу."""

    email: str
    stage: Stage
    why: str
    advice: str

    @property
    def words(self) -> str:
        """Текст тревоги: какой ящик, почему, что делать."""
        return (
            f"ящик {self.email} (направление «{self.stage.value}») встал на паузу сам: "
            f"{self.why}. Новых писем с него нет, письма его переписок ждут. {self.advice}"
        )


async def pause_once(
    session: AsyncSession, sender: SenderModel, reason: str, *, now: datetime
) -> bool:
    """Поставить ящик на паузу, если он ещё пишет. `False` — его уже остановили: другая
    пачка событий рядом, человек. Строка ящика перечитывается под замком до решения: вторая
    пачка ждёт фиксации первой и видит ящик уже стоящим. Замок `FOR NO KEY UPDATE`: отправку
    и добивки по этому ящику (проверку внешнего ключа) он не держит."""
    await session.refresh(sender, with_for_update={"key_share": True})
    if not sender.enabled:
        return False
    disable(sender, reason, now=now)
    return True


#: Пометка тревоги о паузе (слово Anthony 29.10.2026, `ops/alarms.marked`): ящик сам не
#: включится — повод есть всегда.
PAUSED = cause(
    "ящик сам не включится, а письма его переписок ждут",
    "разобрать отказы и жалобы и включить его на экране «Домены рассылки»",
)


async def tell(pauses: Sequence[AutoPause]) -> None:
    """Тревога о каждой паузе, с пометкой последней строкой. Не бросает (`shared/alerts.py`):
    не принял Telegram — строка журнала «ТРЕВОГА НЕ ОТПРАВЛЕНА» с её текстом."""
    for pause in pauses:
        await send_alert(marked(pause.words, PAUSED))
