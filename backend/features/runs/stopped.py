"""Тревога об остановленном прогоне — одна на прогон, а не на попытку.

Прогон закрывается «остановлен» в трёх местах, и у каждого своя причина:
сам прогон — на отказе, который повтор не исправит (`pipeline`); задача
очереди — на таком же отказе до сбора или посреди него (`workers/jobs`);
разбор мёртвых — когда продолжения кончились (`lifecycle`). Тревога уходит
оттуда, где записан статус, и только если эта запись его поменяла
(`RunRepository.stop_run` отвечает, был ли прогон открыт). Задача очереди
закрывает и прогон, который уже закрыл он сам, а вторая тревога о том же
прогоне приучает не читать ни одной.

**Сбой, который будет продолжен, тревоги не шлёт.** Для человека это ещё
не событие: разбор продолжит прогон с последней точки, и три сообщения
о повторах, кончившихся успехом, — шум. Событие — когда продолжать больше
нечем или повтор не поможет.

**Тревога — после фиксации.** Сообщить об остановке, которая откатится
вместе с транзакцией, значит соврать: в базе прогон ещё «идёт», и разбор
продолжит его как ни в чём не бывало.

Причина — те же слова, что на экране прогонов (`runs/reasons.py`): имя
класса исключения нужно журналу, а в телефоне его читать некому.
"""

from __future__ import annotations

from backend.shared.alerts import send_alert


async def tell_stopped(run_id: int, reason: str) -> bool:
    """Сказать человеку, что прогон остановлен и почему. `True` — ушло.

    Не бросает: тревогу зовут из закрытия прогона, и её сбой не должен
    подменить собой причину остановки (`shared/alerts.py`).
    """
    return await send_alert(f"прогон №{run_id} {reason}")
