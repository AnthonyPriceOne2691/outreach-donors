"""Какой сбой прогона лечится повтором, а какой нет.

Одно место на кнопку экрана, консоль и задачу очереди — иначе у них
разойдутся правила, и разойдутся молча.

**Повтор — по умолчанию.** Сеть, таймаут, 5xx после всех повторов
запроса, обрыв соединения с базой — всё это проходит само, а повтор
прогона дешёв: выдача и оплаченные пачки метрик уже сохранены, и
продолжение идёт с последней точки, не покупая сделанное второй раз.

**Не повторяется то, что повтор не исправит:** потолок юнитов и
настройки — решения человека; отказ провайдера с признаком
`permanent` — ключ, права, неверный запрос, непонятный формат ответа.
Повторять их — значит трижды прийти к тому же ответу и трижды его
спрятать. 24.09.2026 прогон №22 упёрся в потолок, упал исключением,
был перезапущен дважды, и в записи стояло «воркер умер».
"""

from __future__ import annotations

from backend.config.startup_checks import ConfigError
from backend.features.runs.budget import CapExceededError

#: Отказы по решению человека: потолок и настройки.
REFUSALS: tuple[type[Exception], ...] = (CapExceededError, ConfigError)


def is_permanent(exc: BaseException) -> bool:
    """Повтор не поможет: закрыть прогон сразу и назвать причину."""
    return isinstance(exc, REFUSALS) or bool(getattr(exc, "permanent", False))


def described(exc: BaseException) -> str:
    """Причина для записи прогона — с типом ошибки: по нему её и ищут."""
    return f"{type(exc).__name__}: {exc}"
