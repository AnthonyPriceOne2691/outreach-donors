"""Причина остановки прогона — словами человека, без кода сервера.

Причину читает человек на экране прогонов, и до 25.09.2026 в неё попадало
имя класса исключения: «остановлен: CapExceededError: Прогон обойдётся
в …», а разбор мёртвых переписывал последнюю строку трассировки целиком —
«задача упала: backend.features.runs.budget.CapExceededError: …». Имя
класса нужно тому, кто ищет по журналу, а не тому, кто решает, что делать
с прогоном: колонку оно раздувало, а объяснить ничего не объясняло.

**Как отличить сообщение для человека.** Язык сервиса русский: все наши
отказы пишутся по-русски и говорят, что делать, — такое сообщение
показывается как есть, без имени класса. Чужое исключение (база, сеть,
библиотека) говорит по-английски и для разработчика; вместо него — общие
слова и имя в скобках, как у любого незнакомого кода на экране:
«техническая ошибка (ReadTimeout)». По имени в скобках сбой находят
в журнале, а полный текст с классом лежит ещё и в отчёте прогона
(`failure`).

Признак — язык, а не то, чей класс: свой `AhrefsError` бывает с сырым
ответом провайдера («batch_metrics: 403 forbidden»), а встроенный
`RuntimeError` из нашего же кода — с человеческой фразой («выдача:
повторы кончились без ответа»). Разделение по модулю ошиблось бы в обе
стороны.

**Записанное раньше не переписывается.** Причины прогонов до этой правки
лежат в базе как были, а показываются по тому же правилу (`readable`):
сырой текст — свидетельство, и чинится его показ, а не он сам.
"""

from __future__ import annotations

import re

#: Общие слова вместо чужого сообщения. Имя класса идёт следом в скобках.
UNKNOWN = "техническая ошибка"

#: Имя исключения: модули строчными через точку и сам класс с заглавной —
#: «CapExceededError», «backend.features.runs.budget.CapExceededError»,
#: «sqlalchemy.exc.MissingGreenlet». Строчное слово с двоеточием
#: («batch_metrics: …») — это уже текст сообщения, а не класс.
_NAME = r"(?:[a-z_][a-z0-9_]*\.)*[A-Z][A-Za-z0-9_]*"

_CYRILLIC = re.compile(r"[А-Яа-яЁё]")

#: Окончания имён исключений. Имя без сообщения трассировка печатает
#: одним словом («TimeoutError»), и без двоеточия за ним нужна уверенность,
#: что это класс, а не первое слово фразы.
_EXCEPTION_ENDINGS = ("Error", "Exception", "Exit", "Interrupt", "Timeout")

#: Строка трассировки целиком: «имя: сообщение» или одно имя.
_LINE = re.compile(rf"(?P<name>{_NAME})(?::[ \t]*(?P<message>.*))?", re.S)

#: Причина, записанная до 25.09.2026. Имя класса стояло сразу за одним из
#: трёх зачинов — так причину писали задача прогона и отчёт («остановлен: »,
#: «сбой, будет продолжен: ») и разбор мёртвых («задача упала: »). Текст
#: исключения кончается там, где разбор продолжал причину своими словами,
#: или в конце строки.
_LEGACY = re.compile(
    r"(?P<lead>остановлен: |будет продолжен: |задача упала: )"
    rf"(?P<name>{_NAME})(?:(?P<colon>:)[ \t]*|(?=[;,]|$))"
    r"(?P<message>.*?)"
    r"(?=; прогон продолжен по сохранённой выдаче|, продолжений \d+ из \d+|$)",
    re.S,
)


def _humane(name: str, message: str) -> str:
    """Сообщение для человека — как есть; чужое — общие слова и имя класса."""
    text = message.strip()
    if _CYRILLIC.search(text):
        return text
    return f"{UNKNOWN} ({name.rsplit('.', 1)[-1]})"


def explained(exc: BaseException) -> str:
    """Причина для записи прогона: без имени класса, если сообщение
    написано человеку, и общими словами, если нет."""
    return _humane(type(exc).__name__, str(exc))


def explained_line(line: str) -> str:
    """То же по последней строке трассировки — так узнаёт причину разбор
    мёртвых: исключения у него нет, есть только то, что сохранила очередь."""
    text = line.strip()
    found = _LINE.fullmatch(text)
    if found is None:
        # Не похоже на строку исключения. Человеческие слова показываются,
        # остальное — общими словами: гадать о классе незачем.
        return text if _CYRILLIC.search(text) else UNKNOWN
    return _humane(found["name"], found["message"] or "")


def _plain(found: re.Match[str]) -> str:
    name = found["name"]
    if found["colon"] is None and "." not in name and not name.endswith(_EXCEPTION_ENDINGS):
        # Одно слово латиницей без двоеточия — начало фразы, а не класс.
        return found[0]
    return found["lead"] + _humane(name, found["message"])


def readable(reason: object) -> str | None:
    """Записанная причина в том виде, в каком её показывает экран.

    Новые причины сюда приходят уже чистыми и проходят без изменений;
    старые теряют имена классов. `None` — причины нет.
    """
    if not isinstance(reason, str) or not reason.strip():
        return None
    return _LEGACY.sub(_plain, reason).strip()
