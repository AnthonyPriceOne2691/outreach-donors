"""Демонстрация — только там, где почта ненастоящая: на боевой базе `demo-seed` не заводит.

Выдуманное пишется прямо в общие таблицы (`demo_data.py`), и до 28.10.2026 защиты от
боевой базы у команды не было. На ней она завела бы включённые демо-ящики этапа доноров
на `.example.test`: строки лимитов у их доменов нет, и фильтр ящиков их пропускает
(`outreach/limits.py`), а остаток у них больше, чем у ящиков в разгоне, — отправка
выбирала бы их первыми, и первые письма вставали бы отказом платформы.

**Боевая база — та, где почта настоящая** (`transport_factory.sends_for_real`): нулевой
транспорт пишет только на выдуманное (`shared/demo.py`), и демонстрация рядом с ним
никому не мешает. Транспорт не распознан — тоже отказ: боевая ли база, тогда не понять.

**Убирать можно всегда.** `--clear` трогает только выдуманное (`demo_data._clear`), и без
этого демонстрацию, заведённую до включения почты, было бы не убрать.
"""

from __future__ import annotations

from backend.config import outreach as cfg
from backend.features.letters.transport import TransportError
from backend.features.letters.transport_factory import sends_for_real


class LiveBaseError(RuntimeError):
    """Демонстрацию сюда не заводят: почта настоящая или не распознана. Сообщение говорит
    почему и что делать."""


def refuse_live_base() -> None:
    """Отказ, если почта настоящая или транспорт не распознан. Ничего не собирает и не пишет."""
    try:
        real = sends_for_real()
    except TransportError as exc:
        raise LiveBaseError(f"боевая ли это база, не понять: {exc}") from exc
    if real:
        raise LiveBaseError(
            "это боевая база — почта уходит по-настоящему "
            f"(OUTREACH_TRANSPORT={cfg.TRANSPORT}). Демо-ящики встали бы в рассылку доноров "
            "первыми: лимитов домена у них нет, а остаток больше, чем у ящиков в разгоне, — "
            "и первые письма вставали бы отказом платформы. Выдуманное заводится при "
            "OUTREACH_TRANSPORT=null; убрать заведённое раньше — outreach demo-seed --clear"
        )
