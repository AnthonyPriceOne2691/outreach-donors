"""Что отвечает вебхук приёма.

Ответ короткий и нужен не платформе — ей достаточно кода 200, — а тому,
кто будет разбираться, почему письмо не попало в диалог. Поэтому в нём
сказано и что приняли, и чем оно оказалось, и привязалось ли.
"""

from __future__ import annotations

from pydantic import BaseModel


class Taken(BaseModel):
    """Итог приёма одного письма."""

    accepted: bool
    #: Номер сохранённого ответа. Пусто у повтора и у отказа.
    reply_id: int | None = None
    #: Чем был ответ: человек, автоответчик, отказ доставки, отписка.
    kind: str | None = None
    #: Удалось ли соотнести с нашим письмом.
    bound: bool = False
    #: Повтор вебхука: письмо с этим номером уже принимали.
    duplicate: bool = False
    #: Разбор ждёт человека.
    needs_review: bool = False
    #: Почему не приняли или почему ждёт человека — словами.
    reason: str | None = None
