"""Где проходит граница между выдуманным и боевым.

Зона `.example.test` зарезервирована под примеры, и писем туда не уходит.
Ею помечено всё, что заведено для показа экранов до появления боевых
доменов, — и по ней же нулевой транспорт понимает, что отправлять можно.

**Признак один на весь сервис.** Второй экземпляр этой строки означал бы,
что однажды заглушка сочтёт боевой домен выдуманным: цена такой ошибки —
письмо, отправленное в никуда, или, хуже, реальному человеку из
проверочного прогона.
"""

from __future__ import annotations

#: Зона, зарезервированная под примеры (RFC 2606).
SUFFIX = ".example.test"


def is_demo(host: str) -> bool:
    """Выдуманный ли это домен."""
    return host.strip().lower().endswith(SUFFIX)


def is_demo_address(email: str) -> bool:
    """Выдуманный ли адрес — по домену почты."""
    return is_demo(email.split("@", 1)[-1])
