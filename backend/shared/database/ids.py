"""Номер строки из адреса — только в пределах столбца.

Первичные ключи у нас `integer`, четыре байта. Номер больше 2 147 483 647
база не сравнивает, а отказывает переполнением, и маршрут отвечал
пятисоткой: `/api/donors/99999999999` — «Internal Server Error» (замер
25.09.2026). Такой строки нет по построению — это «не найдено», а не
поломка сервера, и ответ должен быть тем же, что у любого несуществующего
номера.
"""

from __future__ import annotations

#: Самый большой номер, который помещается в столбец `integer`.
INT4_MAX = 2**31 - 1


def storable(number: int) -> bool:
    """Может ли строка с таким номером существовать. Номера — с единицы."""
    return 1 <= number <= INT4_MAX
