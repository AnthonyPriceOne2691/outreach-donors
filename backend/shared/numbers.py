"""Числа словами экрана и сообщений: разряды — неразрывным пробелом.

Обычный пробел рвёт число переносом строки — в Telegram, на «Обзоре», в тексте отказа: «1»
в конце одной строки и «000 000» в начале следующей. До 19.10.2026 так писали отказы потолка
прогона и ручной цены, а неразрывный жил копиями в модулях (`donors/export`, `runs/ahrefs_cap`).
Помощник один — и копии не разъедутся.
"""

from __future__ import annotations

#: Разделитель разрядов — неразрывный пробел.
NBSP = " "


def spaced(number: int) -> str:
    """Число с разрядами, как на экране: «1 000 000» — неразрывным пробелом."""
    return f"{number:,}".replace(",", NBSP)
