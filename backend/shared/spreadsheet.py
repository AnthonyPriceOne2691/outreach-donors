"""Ячейка выгрузки, которую таблица не исполнит как формулу.

Выгрузки сервиса открывают в Excel и Google Sheets, а текст в них бывает чужим:
слова из письма донора или лида, вписанное человеком. Ячейка, начатая с `=`, `+`,
`-` или `@`, для таблицы — формула: `=HYPERLINK(...)` при открытии файла вытащил бы
соседние ячейки — адреса других лидов (ревью «Продаж» #160, OWASP «CSV Injection»).
Табуляция и перевод строки в начале ячейки таблица тоже читает по-своему.

Одно правило на все выгрузки: лидов (`replies/lead_handoff.py`), доноров
(`donors/export.py`, 12.10.2026 — оплата и валюта там тоже слова из письма),
рекламодателей (`crawl/advertiser_export.py`) и поиска контактов по файлу
(`contacts/file_sweep.py`). Отчёт загрузки доноров собирает браузер, и то же
правило повторено там (`frontend/src/advertisers/BulkDonors.tsx`).
"""

from __future__ import annotations

#: С чего начинается формула или служебный знак в Excel и Google Sheets (OWASP).
FORMULA_START = ("=", "+", "-", "@", "\t", "\r", "\n")


def inert(value: object) -> object:
    """Строка, которую таблица не исполнит: ведущий апостроф — по OWASP. Не строки
    (числа, даты) и обычный текст — как есть."""
    if isinstance(value, str) and value.startswith(FORMULA_START):
        return f"'{value}"
    return value
