/**
 * Второй шанс цитате — строкой отчёта прогона под режимом судьи (судья сегмента v5): у скольких
 * сайтов цитата первого ответа модели не нашлась в тексте сайта и модель спросили второй раз, и у
 * скольких из них цитата нового ответа нашлась. Числа пишет сервер (`report.judge.quote_retried`,
 * `quote_retry_held` — суммой по проходам прогона); у пересуда свои — в его итоге
 * (`SegmentSitesRejudge`). Второго вопроса не было или прогон судили до v5 — строки нет.
 *
 * **Строкой судьи, а не в окне «Расход и смета».** Число говорит, на чём стоит вердикт: факты второго
 * ответа или «на проверку» словами «цитата не нашлась», — и читается рядом с режимом и разбором
 * описания, без лишнего окна (стенд прогона видел эти числа только в базе). Токены второго вопроса
 * сервер отдельно не считает: они в токенах вердикта, то есть уже в строке судьи окна расхода, а
 * сайты в таблице статей были бы чужой единицей без сметы — её колонки пишет сервер.
 */

import { Text } from '@mantine/core';

import { quoteRetries, quoteRetryWords } from './segmentData';

export function SegmentQuoteRetry({ report }: { report: Record<string, unknown> }) {
  const found = quoteRetries(report.judge);
  if (found === null) return null;
  const words = quoteRetryWords(found);
  return (
    <Text size="sm" c="dimmed">
      {`${words.charAt(0).toUpperCase()}${words.slice(1)}.`}
    </Text>
  );
}
