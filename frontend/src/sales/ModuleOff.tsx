/**
 * «Модуль продаж выключен» — строкой под шапкой раздела, на любой вкладке и в мастере загрузки.
 *
 * Находка QA соседей на проде: модуль был выключен, а все вкладки и «Загрузка базы» выглядели
 * рабочими — о выключенном модуле говорил только отказ сборки очереди, да ещё именем
 * настройки. Включён ли модуль, называет сервер в списке гипотез (`module_enabled`): его раздел
 * грузит на каждой вкладке. Вид — плашкой в одну строку, заголовок в начале абзаца, как у
 * «Письма переписки ждут свой ящик» (`threads/ThreadMailLine`); янтарь — «нужно внимание».
 * Имени настройки на экране нет: модуль включает администратор.
 *
 * Строка — только когда сервер прямо сказал «выключен»: ответ без поля (старый сервер посреди
 * выкладки) не пугает «письма не уходят».
 */

import { Alert, Text } from '@mantine/core';

import type { HypothesesView } from '../api/salesTypes';

export function ModuleOff({ view }: { view: HypothesesView }) {
  if (view.module_enabled !== false) return null;
  return (
    <Alert color="yellow" py={6} px="sm" mx="md" className="salesModuleOff">
      <Text span size="sm" fw={600}>
        Модуль продаж выключен
      </Text>{' '}
      —{' '}
      <Text span size="sm">
        письма не уходят, разбор и передача не идут
      </Text>
    </Alert>
  );
}
