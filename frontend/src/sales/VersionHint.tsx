/**
 * Внутренний номер версии — в «i» у своей строки, а не на виду.
 *
 * «Версия базы `kb-3f2a…`» и «Версия `chain-…`» стояли строками экрана (проверка прода
 * 10.11.2026). Отпечаток человеку ничего не говорит: по нему сборка, черновик агента и калибровка
 * узнают текст, а нужен он только при разборе с разработчиком. Правило владельца 10.11: на виду —
 * коротко и словами для человека, технические коды — в «i». На виду остаётся смысл строки
 * («цепочка полна», «агент видит N из M»).
 *
 * **Окошком, а не всплывающей подсказкой** (`interactive`): номер передают разработчику, а
 * подсказку по наведению не выделить и не скопировать — окошко по нажатию держится.
 *
 * **Своим значком, а не абзацем соседней «i»**: пояснения вкладок — всплывающие подсказки, их
 * открывает и фокус, и ими же мерит контраст каталог экранов (`scripts/ui_screens_sales*.py`,
 * `hint_probe`); окошко фокусом не открывается, и подсказка, ставшая окошком, выпала бы из замера.
 */

import { Text } from '@mantine/core';
import type { ReactNode } from 'react';

import { InfoHint } from '../components/InfoHint';

interface Props {
  /** Чья версия — имя значка и начало строки окошка: «Версия базы». */
  name: string;
  /** Номер версии, как его назвал сервер: `kb-…`, `chain-…`. */
  version: string;
  /** Зачем она — одной фразой после номера. */
  children: ReactNode;
}

/** Номер — одной строкой: по дефису он рвался на «chain-» и отпечаток (снимок 390 px). */
const WHOLE = { whiteSpace: 'nowrap' } as const;

export function VersionHint({ name, version, children }: Props) {
  return (
    <InfoHint name={name} width={300} interactive>
      <Text size="sm" className="versionLine">
        {name} — <code style={WHOLE}>{version}</code>. {children}
      </Text>
    </InfoHint>
  );
}
