/**
 * Пустые разделы базы знаний — плашкой над таблицей: что агент сделает без них («Кейсов на
 * английском нет — агент не приведёт ни одного примера»).
 *
 * Агент работает и при пустых кейсах или ценах — промпт велит не называть цен, судья ловит
 * выдуманное, — но экран об этом молчал. Слова и правило — сервера (`kb_gaps.py`, тем же
 * правилом, каким агент берёт записи: нет на языке письма — берёт на другом и переводит).
 * Все записи выключены — одна строка, а не четырнадцать: агент не видит ни одной.
 *
 * **Одинаковый исход — одной строкой** (замечание владельца 10.11.2026: «пояснения — не простынёй»;
 * аудит того же дня: из восьми строк плашки шесть кончались словами «агент возьмёт записи на русском
 * и переведёт»). Строки собирает сервер (`gap_lines`): «Пусто на английском: «о компании», услуги,
 * кейсы — агент возьмёт записи на русском и переведёт»; раздел, которого нет ни на одном языке, —
 * строкой на все языки сразу. Экран слова не разбирает. В записанных ответах старых тестов строк
 * нет — тогда строка у каждого раздела, как было.
 */

import { Alert, List } from '@mantine/core';

import type { KbView } from '../api/salesTypes';

export function KbGaps({ view }: { view: KbView }) {
  if (view.total === 0 || view.gaps.length === 0) return null;
  if (view.active === 0) {
    return (
      <Alert color="yellow" title="Агент не видит ни одной записи" mx="md">
        Все записи выключены — агент пишет без базы знаний: без услуг, кейсов и цен.
      </Alert>
    );
  }
  const lines = view.gap_lines ?? view.gaps.map((gap) => gap.words);
  return (
    <Alert color="yellow" title="Пустые разделы" mx="md">
      <List size="sm" spacing={2} aria-label="Пустые разделы">
        {lines.map((line) => (
          <List.Item key={line}>{line}.</List.Item>
        ))}
      </List>
    </Alert>
  );
}
