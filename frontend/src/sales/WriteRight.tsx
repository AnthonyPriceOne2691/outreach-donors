/**
 * Тексты продаж меняет тот, у кого есть право отправки писем, — как письма ядра.
 *
 * Шаг цепочки, запись базы знаний и отправитель уходят адресату так же, как письмо, а
 * сборка очереди пишет письма и тратит модель: сервер пускает сюда только с правами
 * `sales` и `send` (`api/sales/chain.py`, `kb.py`, `queue.py`). Без права поля и кнопки
 * записи закрыты, а рядом — одна строка почему, образцом общего экрана писем
 * (`letters/LetterPreview`): смотреть и показывать письмо можно всем.
 *
 * Одно место на вкладки и окна раздела: шесть одинаковых строк разошлись бы на первой
 * правке одной из них. Права в интерфейсе — удобство, а не защита: проверяет сервер.
 */

import { Text } from '@mantine/core';
import type { MantineSpacing } from '@mantine/core';

import { useSession } from '../auth/AuthProvider';

/** Можно ли менять тексты продаж и собирать очередь. */
export function useMayWrite(): boolean {
  return useSession().can('send');
}

/** Почему запись закрыта. `what` — кто что делает: «Правит цепочку», «Собирает очередь»;
 *  поле `px` — кромка текста вкладки, в окне его нет. */
export function WriteRight({ what, ...edge }: { what: string; px?: MantineSpacing }) {
  return (
    <Text size="xs" c="dimmed" {...edge}>
      {what} тот, у кого есть право отправки писем. Смотреть можно всем.
    </Text>
  );
}
