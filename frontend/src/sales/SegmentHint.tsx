/**
 * Подсказка к описанию сегмента: кто подходит, кто нет и чем их отличить — шаблоном для любой
 * ниши.
 *
 * Тест прогона: судья ошибался в сторону принятия — справочники и порталы проходили как свои,
 * а описанием гипотезы стояла цель теста («проверить рассылку по сайтам, связанным с …»), а не
 * профиль сайта, которому пишем. Судья читает описание буквально: ему нужно, **кто подходит**,
 * **кто нет** и **чем отличить** — по тексту сайта, а не по теме. Чаще всего «нет» — одни и те
 * же виды сайтов в любой нише: справочники и каталоги, агрегаторы, тендеры, госорганы, СМИ и
 * обзоры, форумы и доски объявлений.
 *
 * Свёрнута, пока её не открыли; «Вставить шаблон» — только в пустое поле: набранное описание
 * подсказка не затирает.
 */

import { Button, Collapse, Group, List, Stack, Text } from '@mantine/core';
import { useId, useState } from 'react';

/** Шаблон описания: три части, в угловых скобках — что вписать своё. */
export const SEGMENT_TEMPLATE = [
  'Кто подходит: <какие это сайты — компания сама делает и продаёт то, о чём гипотеза: свои ' +
    'услуги или товары, свои цены, заказ на сайте; страна, язык, размер — если важны>.',
  'Кто не подходит: справочники и каталоги компаний, агрегаторы и маркетплейсы, сайты тендеров ' +
    'и закупок, госорганы и ассоциации, СМИ, блоги, обзоры и рейтинги, форумы, доски объявлений ' +
    'и вакансий, <свои исключения>.',
  'Чем отличить: у подходящего — свои услуги или товары, «заказать», «наши работы», ' +
    'контакты компании; у неподходящего — списки чужих компаний, «добавить компанию», поиск по ' +
    'городам, тендеры, новости о рынке.',
].join('\n');

export function SegmentHint({
  draft,
  onDraft,
}: {
  draft: string;
  onDraft: (text: string) => void;
}) {
  const [open, setOpen] = useState(false);
  const panel = useId();
  return (
    <Stack gap={6}>
      <Group gap="sm">
        <Button
          variant="subtle"
          size="compact-sm"
          className="press"
          aria-expanded={open}
          aria-controls={panel}
          onClick={() => setOpen((was) => !was)}
        >
          {open ? 'Скрыть подсказку' : 'Как описать сегмент'}
        </Button>
        {draft.trim() === '' && (
          <Button
            variant="default"
            size="compact-sm"
            className="press"
            onClick={() => onDraft(SEGMENT_TEMPLATE)}
          >
            Вставить шаблон
          </Button>
        )}
      </Group>
      <Collapse in={open} id={panel}>
        <Stack gap={6} maw={720}>
          <Text size="sm">
            Судья сравнивает с описанием текст сайта — выдачу и главную. Опишите сайт, которому
            пишете, а не цель прогона: «проверить рассылку по …» судья прочтёт как сегмент.
          </Text>
          <List size="sm" spacing={4}>
            <List.Item>
              <b>Кто подходит</b> — какие это сайты и чем они живут: компания сама оказывает услугу
              или продаёт товар.
            </List.Item>
            <List.Item>
              <b>Кто не подходит</b> — в любой нише это обычно справочники и каталоги, агрегаторы и
              маркетплейсы, тендеры и закупки, госорганы, СМИ и обзоры, форумы и доски объявлений.
            </List.Item>
            <List.Item>
              <b>Чем отличить</b> — что на сайте видно: свои услуги и цены у подходящего, списки
              чужих компаний и «добавить компанию» — у справочника.
            </List.Item>
          </List>
        </Stack>
      </Collapse>
    </Stack>
  );
}
