/**
 * Ответы без письма — ответ `GET /api/replies/unbound` (вкладка «Не привязаны» «Диалогов»).
 *
 * Своим файлом, а не в `types.ts`: тот у потолка длины, а карточке 11.11.2026 добавилась
 * короткая метка причины.
 */

import type { ReplyAttachment, ReplyKind } from './types';

/** Ответ, который не привязался ни к одному нашему письму: ни метка в адресе,
 *  ни заголовки цепочки не привели к письму. Отправителя по нему ищет человек. */
export interface UnboundReply {
  id: number;
  received_at: string;
  /** Адрес отправителя целиком: это внутренний экран, по нему отправителя и ищут. */
  from_email: string | null;
  /** На какие адреса пришло: конверт, «кому», копия — наш первым. Пусто у
   *  ответов, принятых до того, как адреса стали хранить. */
  to: string[];
  subject: string | null;
  kind: ReplyKind;
  /** Начало того, что написал человек, — одной строкой и без цитаты. */
  preview: string;
  /** Текст целиком — в раскрытой строке. */
  text: string;
  attachments: ReplyAttachment[];
  /** Причина кодом сервера (`no_label`, `foreign_thread`, `bad_signature`,
   *  `no_such_letter`); пусто — не записана. На экран идут слова, а не код. */
  reason: string | null;
  /** Причина словами сервера целиком — и что с таким ответом делать: кого по нему искать,
   *  сервер называет по направлению ответа (донора, рекламодателя, лида). */
  reason_text: string;
  /** Та же причина меткой в несколько слов — её несёт строка списка («Почему не привязан:
   *  …»), слова целиком — в «i». Поля нет — сервер старше метки: в строке слова целиком. */
  reason_short?: string;
}

/** Страница ответов без письма: размер страницы называет сервер. */
export interface UnboundView {
  rows: UnboundReply[];
  /** Сколько их всего, а не на этой странице. */
  total: number;
  page: number;
  limit: number;
}
