/** Очередь, которая уходит сама: «Отправить очередь» с отметкой «дальше — сама» — и остаток
 *  уходит каждый день, по письму с ящика с паузой, пока очередь не кончится или её не
 *  остановят (замечание тест-группы 29.10.2026). */
export interface QueueAutosend {
  /** Можно ли включить: рубильник сервиса включён и этап — доноры или рекламодатели. */
  available: boolean;
  /** Идёт ли запуск; поля ниже — его, а у кончившегося — последнего запуска. */
  running: boolean;
  since: string | null;
  started_by: string | null;
  /** Первых писем очереди ушло с запуска — любым путём. */
  sent: number;
  /** Чем кончился последний проход — словами сервера. */
  state: string | null;
  passed_at: string | null;
  /** Почему проходы стоят при идущем запуске: рубильник выключен. */
  off: string | null;
  stopped_at: string | null;
  stopped_by: string | null;
  stop_reason: string | null;
}

/** Срок очереди из прогноза рассылки (`GET /letters/forecast`, `queue_eta`): когда уйдёт последнее
 *  письмо, стоящее в очереди сейчас, — у очереди, которая уходит сама, по паузе ящиков и окну. */
export interface QueueEta {
  /** День ухода последнего письма; пусто — срока нет (почему — `words`). */
  day: string | null;
  /** Дней отправки до него, считая сегодня. */
  sending_days: number | null;
  hours: number | null;
  words: string;
}
