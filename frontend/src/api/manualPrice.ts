/** Цена руками: цена, которую агентство знает само, и донор, заведённый вручную
 *  (`donors/manual_price.py`, 07.10.2026).
 *
 *  Требование Этапа 2 — «по кому запускаем — только доноры с известной ценой (из
 *  базы или заведённые вручную)»: до этого цена бралась только из ответа донора.
 *  Отдельным файлом: `types.ts` упёрся в свой потолок. Запросы — рядом
 *  с остальными запросами доноров (`runs.ts`): этот файл `types.ts` читает сам,
 *  и запрос, вернувший отсюда карточку донора, замкнул бы их в круг. */

/** Откуда последняя цена донора: из ответа на письмо или вписал человек.
 *  `null` — цена записана до 07.10.2026, когда её давал только ответ. */
export type PriceSource = 'reply' | 'manual';

/** Откуда цена — поля карточки донора, которых нет у строки таблицы. Поля
 *  нет — сервер старше 07.10.2026: значит, цена из ответа. */
export interface PriceOrigin {
  last_price_source?: PriceSource | null;
  /** Заметка «откуда цена» и кто её вписал — только у ручной цены. */
  last_price_note?: string | null;
  last_price_by?: string | null;
  /** Донор заведён вручную, с ценой, а не принят в очереди прогона, — кем. */
  entered_by?: string | null;
}

/** Можно ли вписать цену руками — поле карточки донора. */
export interface PriceRefusal {
  /** Почему цену сейчас не записать — словами отказа «Записать цену»
   *  (`manual_price.price_refusal`); `null` — запишется. Поля нет — сервер
   *  старше 08.10.2026: отказ придёт по нажатию, как раньше. */
  price_refusal?: string | null;
}

/** Цена, которую человек знает сам. Проверяет сервер и отказывает словами:
 *  цена уходит строкой, как вписана, — «1,200» он не угадывает, а называет. */
export interface PriceBody {
  price: string;
  currency: string;
  /** Откуда цена: «прайс агентства», «LinkDetective». `null` — не сказали. */
  note: string | null;
}

/** «Завести донора вручную»: домен или адрес сайта — сервер приводит его
 *  к корню, как у прогона. */
export interface ManualDonorBody extends PriceBody {
  host: string;
}

/** Что вышло из «Завести донора вручную». */
export interface EnteredDonor {
  donor_id: number;
  host: string;
  /** Донором домен стал сейчас; `false` — уже был донором, записана цена. */
  created: boolean;
  /** Годен по порогам — обход Этапа 2 его берёт. Донор, принятый раньше, мог
   *  стать негодным после обновления метрик: цена записана, обхода не будет. */
  suitable: boolean;
  /** Деньги строкой, как у остальных цен: сервер не теряет копейки. */
  price: string;
  currency: string;
}
