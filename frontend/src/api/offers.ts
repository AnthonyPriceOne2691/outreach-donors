/** Цены списком: каждая цена, которую донор назвал в ответе (`replies/offers.py`).
 *
 *  Приходит у ответа (`IncomingCard.offers`) и у донора — все цены того же
 *  ответа, что последняя цена (`DonorFullCard.last_offers`). `null` или поля
 *  нет — ответ разобран до 06.10.2026, когда списка ещё не было; `[]` — цен
 *  в ответе не названо. Отдельным файлом: `types.ts` упёрся в свой потолок. */

/** Одна цена из ответа. Продукт и ниша — словами донора, как он их написал:
 *  это цитата письма, а не наш справочник. */
export interface Offer {
  product: string;
  niche: string | null;
  /** Деньги строкой, как у остальных цен: сервер не теряет копейки. */
  price: string;
  currency: string | null;
  /** Цена за срок — месяц или год; `null` — разовая. */
  period: 'month' | 'year' | null;
}
