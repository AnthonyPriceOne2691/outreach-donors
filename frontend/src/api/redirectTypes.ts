/**
 * Переадресация в диалоге рекламодателя (16.11.2026): ответ назвал другой адрес — «пишите на
 * partners@…», — и то же письмо уходит туда в той же переписке. Что решено и что с письмом,
 * говорит сервер словами (`backend/api/threads/schemas.py`, `RedirectCard`); экран показывает их
 * как есть и своих правил не держит. Типы — своим файлом: `types.ts` у своего потолка длины.
 */

/** Шаг письма переадресации в переписке — как у сервера (`letters/chain.py`, `REDIRECT_STEP`):
 *  лента называет письмо по шагу. */
export const REDIRECT_STEP = 300;

/** Состояние словом: `checking` — проверяем ответ; `waiting` — письмо ждёт отправки; `sent` —
 *  переслали; `bounced` — письмо не дошло; `stopped` — снято; `refused` — не пересылаем (почему —
 *  в словах сервера). */
export type RedirectState = 'checking' | 'waiting' | 'sent' | 'bounced' | 'stopped' | 'refused';

export interface RedirectCard {
  state: RedirectState;
  /** Слова сервера одной строкой — показываются как есть. */
  words: string;
  /** Адрес из ответа, дословно. Пусто — ещё не выбран. */
  address: string | null;
  /** Ответ, который назвал адрес. */
  reply_id: number;
  /** Письмо на этот адрес — оно же в ленте переписки. Пусто — письма нет. */
  letter_id: number | null;
  /** Пометка: адрес не на домене рекламодателя. */
  note: string | null;
}
