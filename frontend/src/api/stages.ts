/**
 * Этап строки, которую отдаёт сервер, и его пометка словами.
 *
 * `Stage` — все этапы сервера (`core.domain.Stage`): диалог, запись стоп-листа
 * и сводка писем бывают и у продаж. `LetterStage` (`types.ts`) — этапы экрана писем
 * почты (`core.stages.MailStage`): сборка очереди из прогонов, текст письма файлом,
 * переключатель этапов почты. Письма продаж собирает и показывает модуль продаж (свои
 * экраны и вкладка «Очередь писем»), а уходят они — и ответ лиду из переписки — мостом
 * почты к модулю продаж; не подключены продажи — сервер отказывает словами, чего не
 * хватает. Агент строит переключатель этапов по реестру сервера. Словари экранов почты
 * продаж не знают нарочно: запись о продажах там была бы текстом экрана, которого нет.
 * Сверку с сервером держит `tests/test_sales_stage_screens.py`.
 *
 * Своим файлом, а не в `types.ts`: тот у потолка длины.
 */

export type Stage = 'donors' | 'advertisers' | 'sales';

/** Пометка этапа в шапке переписки. У донора её нет: доноры — основной поток,
 *  и пометка у каждого диалога была бы шумом. */
export const THREAD_STAGE_NOTES: Record<Stage, string> = {
  donors: '',
  advertisers: 'рекламодатель',
  sales: 'продажи',
};

/**
 * Этап на общих экранах — только тому, кто его видит: продажи — с правом «Продажи»
 * (решение Anthony 10.10.2026, П2). Сервер отказывает сам: в общих списках и числах
 * продаж без права нет, а письмо или переписка продаж по номеру — 403 словами. Экран
 * не предлагает того, в чём сервер откажет. `sales` — `can('sales')` сессии.
 */
export function stageShown(stage: string, sales: boolean): boolean {
  return stage !== 'sales' || sales;
}

/** Состояния диалога, которые бывают только у переписки продаж. */
const SALES_STATES: ReadonlySet<string> = new Set(['sales_pending']);

/** Состояние диалога на экране: состояния продаж — тоже только с правом «Продажи». */
export function stateShown(state: string, sales: boolean): boolean {
  return !SALES_STATES.has(state) || sales;
}
