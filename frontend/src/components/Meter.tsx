/**
 * Потрачено из лимита — одна полоса на весь фронт.
 *
 * Общий компонент по той же причине, что и плитка: полоса расхода стоит
 * на главной и на экране расхода, и две похожие разошлись бы цветом
 * и порогами при первой правке одной из них.
 *
 * Заполнение несёт тяжесть: акцент, пока до лимита далеко, янтарь с 80 %,
 * роза, когда лимит выбран. Дорожка — светлая ступень того же цвета,
 * а не серое умолчание Mantine: серая дорожка на стекле читается чужой
 * деталью, а своего цвета — продолжением полосы.
 *
 * Число рядом пишется словами на экране: полоса — подсказка глазу,
 * а не единственный способ узнать, сколько потрачено.
 */

import { Progress } from '@mantine/core';

/** С этой доли полоса янтарная: до лимита осталась пятая часть. */
const WARN_SHARE = 0.8;

interface Props {
  spent: number;
  cap: number;
  /** Что это за полоса — для программы чтения с экрана. */
  label: string;
}

export function Meter({ spent, cap, label }: Props) {
  const share = cap > 0 ? spent / cap : 0;
  const tone = share >= 1 ? 'rose' : share >= WARN_SHARE ? 'amber' : 'accent';
  return (
    <Progress
      className="meter"
      data-tone={tone}
      value={Math.min(100, share * 100)}
      color="var(--meter-fill)"
      radius="xl"
      size="sm"
      aria-label={label}
    />
  );
}
