/**
 * Длинное имя — домен, адрес страницы — переносится по своим швам, а не
 * посреди слова.
 *
 * Замечание 06.10.2026: длинные домены в колонке «Донор» рвались как попало —
 * «analysis.example.te / st», «sandbonuses.co. / uk», а анкор-адрес —
 * «promotions/w / elcome». Имя в ячейке переносится где угодно (`cellName`,
 * `overflow-wrap: anywhere`), но «где угодно» — это там, где кончилось место:
 * точку и косую черту браузер швом не считает, шов для него — только пробел
 * и дефис. Здесь перед точкой, «?», «&», «=» и «#» и после «/» стоит `<wbr>` —
 * место переноса без знака: имя копируется и ищется по странице как было.
 * Посреди части строка рвётся, только если сама часть шире колонки.
 *
 * Замер в браузере шрифтом таблиц (14 px; 397 доменов, собранных из слов
 * по образцу доноров: поддомен, слова слитно и через дефис, зоны вида
 * «.co.uk»): в колонке 144 px разрывов посреди слова 53 вместо 129, строк
 * 674 вместо 615; в 184 px — 17 вместо 65; в 253 px — ни одного вместо 8.
 * Лишние строки — цена: часть, которая не влезает в строку вслед за
 * соседней, переносится на новую целиком, а не обрубком.
 */

import { Fragment } from 'react';

/** «.com.au», «.co.uk» — одна зона: без склейки «.au» оставалась одна на
 *  последней строке. Двухбуквенная зона страны за коротким уровнем перед ней. */
const ZONE_TAIL = /^\.[a-z]{2}\/?$/i;
const ZONE_HEAD = /^\.[a-z]{2,3}$/i;

/** Метка шва на время разбора: в домене и адресе её не бывает. */
const SEAM = '\u0000';

/** Куски имени между швами: «news.example.com» — «news», «.example», «.com».
 *  «//» после схемы не рвётся: «https:/» на одной строке и «/» на другой
 *  читались бы как два адреса. Шов после «/» ставится заменой, а не
 *  ретроспективной проверкой (`(?<=…)`): её не знает Safari до 16.4, и
 *  такая регулярка роняла бы экран целиком, а не один перенос. */
export function seamsOf(text: string): string[] {
  const marked = text.replace(/[.?&=#]/g, (mark) => SEAM + mark).replace(/\/(?!\/)/g, `/${SEAM}`);
  const pieces = marked.split(SEAM).filter((piece) => piece !== '');
  return pieces.reduce<string[]>((joined, piece) => {
    const previous = joined[joined.length - 1];
    if (previous !== undefined && ZONE_TAIL.test(piece) && ZONE_HEAD.test(previous)) {
      joined[joined.length - 1] = previous + piece;
    } else {
      joined.push(piece);
    }
    return joined;
  }, []);
}

export function Seams({ text }: { text: string }) {
  return seamsOf(text).map((piece, index) => (
    // Куски одного имени не переставляются и не меняются местами — номер
    // и есть их место.
    <Fragment key={index}>
      {index > 0 ? <wbr /> : null}
      {piece}
    </Fragment>
  ));
}
