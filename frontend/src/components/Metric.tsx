/**
 * Число с подписью — плитка, из которых собраны сводки на экранах.
 *
 * Общий компонент, а не четыре похожих на четырёх экранах: похожие
 * расходятся. Сначала у них разное выравнивание, потом разные отступы,
 * а через месяц сводка прогона и сводка расхода выглядят из разных
 * приложений.
 *
 * Выравнивание по центру: в плитке живёт одно число, и колонка чисел,
 * прижатых влево, читается как таблица без заголовков.
 *
 * **Числа ряда стоят на одной линии.** Плитка — строки общей сетки
 * ряда (`metricTile`, подсетка): подпись, число, пояснение. Подпись в две
 * строки у одной плитки раньше сдвигала её число на 17 px вниз против
 * соседних, а плитки в колонках разной высоты выходили 86 и 107 px (аудит
 * 25.09.2026, №22). Теперь строка сетки одна на весь ряд, и её высоту
 * задаёт самая длинная подпись.
 *
 * **Нет пояснений в ряду — нет и строки под них** (26.09.2026). Третья
 * строка сетки была у плитки всегда и держала под числом пустую полосу:
 * на «Отборе» пять плиток из шести стояли с содержимым выше середины
 * (17 px сверху, 38 снизу). Строку пояснения теперь заводит пояснение
 * хоть одной плитки сетки (`metricHint`, правило в `glass.css`).
 */

import { Card, Text } from '@mantine/core';
import type { ReactNode } from 'react';
import { Link } from 'react-router-dom';

interface Props {
  title: string;
  value: ReactNode;
  hint?: ReactNode;
  /** Цвет числа. По умолчанию обычные чернила: цветом помечают то,
   *  на что смотреть, а если помечено всё — не помечено ничего. */
  color?: string | undefined;
  /** Куда ведёт плитка. С адресом плитка — ссылка целиком: число на главной
   *  — это вход в экран, где с ним работают, и искать рядом отдельную
   *  ссылку «перейти» незачем. */
  to?: string | undefined;
}

export function Metric({ title, value, hint, color, to }: Props) {
  // Три строки — прямые дети плитки: подсетка раскладывает только их.
  const body = (
    <>
      {/* Подпись — полными чернилами. Она стоит в верхней части плитки,
          на блике стекла, и приглушённый тон там не держал норму в тёмной
          теме: 4,44 : 1, при том что пояснение того же тона внизу плитки
          давало 6,03 (замер 23.09). Иерархию держат размер и вес числа. */}
      <Text size="xs" c="var(--ink)" className="metricTitle">
        {title}
      </Text>
      <Text fw={600} fz="xl" c={color ?? 'inherit'}>
        {value}
      </Text>
      {hint !== undefined && (
        <Text size="xs" c="dimmed" className="metricHint">
          {hint}
        </Text>
      )}
    </>
  );

  if (to === undefined) {
    return (
      <Card className="glassQuiet metricTile" p="md">
        {body}
      </Card>
    );
  }
  return (
    <Card component={Link} to={to} className="glassQuiet metricTile metricLink press" p="md">
      {body}
    </Card>
  );
}
