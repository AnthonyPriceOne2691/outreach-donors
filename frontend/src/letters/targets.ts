type Funnel = Record<string, number>;

/**
 * Ступени воронки по порядку и что делать, если на ступени ноль. Воронка
 * накопительная: «с адресом 0» после нуля на цене — не про адреса, и совет
 * «ищите контакты» отправил бы платить за поиск впустую. Поэтому называется
 * одна ступень — первая, где адресаты кончились.
 */
const ADVERTISER_STOPS: [string, string][] = [
  ['рекламодателей', 'их ещё нет — рекламодателей находит обход доноров с ценой'],
  ['со ссылкой', 'ни у кого нет найденной ссылки целиком, письмо не под что писать'],
  [
    'цена донора свежая',
    'сначала нужны ответы доноров со свежей ценой, оффер «мы дешевле» без неё не пишется',
  ],
  ['с адресом', 'пора искать контакты рекламодателей'],
  ['вне стоп-листа', 'все оставшиеся в стоп-листе'],
  ['ещё не писали', 'написаны все'],
];

const NICHE_STOPS: [string, string][] = [
  ['бизнесов ниши', 'их ещё нет — бизнесы ниши собираются в конце каждого прогона'],
  ['решено «пишем»', 'никому не сказали «пишем» — решение на экране «Рекламодатели»'],
  ['из них с адресом', 'адрес ищется сам после «пишем» — дождитесь поиска контактов'],
  [
    'ещё не писали',
    'написаны все — или у их прогонов нет принятого донора со свежей ценой, примера площадки',
  ],
];

function stopOf(funnel: Funnel, stops: [string, string][]): string | null {
  const found = stops.find(([step]) => (funnel[step] ?? 0) === 0);
  return found === undefined ? null : `Кончились на ступени «${found[0]}»: ${found[1]}.`;
}

/**
 * Кому прежнее письмо не дошло — словами, когда такие есть (28.09.2026).
 * Не дошедшее письмо «писали» не считается: следующее уходит на следующий
 * адрес, и такие адресаты уже внутри «ещё не писали». У кого адреса
 * кончились — отдельно: из «ещё не писали» они выпали, и без этой фразы
 * их было бы не отличить от тех, кому письмо дошло. Сервер шлёт обе строки
 * только ненулевыми.
 */
function earlierLetters(funnel: Funnel, target: LetterTarget): string | null {
  const next = funnel['из них на следующий адрес'] ?? 0;
  const gone = funnel['адреса кончились'] ?? 0;
  const said: string[] = [];
  if (next > 0) said.push(`Из них на следующий адрес — ${next}: прежнее письмо не дошло.`);
  if (gone > 0) {
    const whom =
      target === 'donors'
        ? plural(gone, 'донора', 'доноров', 'доноров')
        : plural(gone, 'рекламодателя', 'рекламодателей', 'рекламодателей');
    // Вписать адрес руками можно только донору — в его карточке.
    const cure = target === 'donors' ? ' — новый адрес вписывают в карточке донора' : '';
    said.push(`У ${gone} ${whom} адреса кончились: прежние письма не дошли${cure}.`);
  }
  return said.length > 0 ? said.join(' ') : null;
}

const EMPTY: Record<LetterTarget, (n: (step: string) => number, funnel: Funnel) => string> = {
  donors: (n) =>
    `Подходящих доноров ${n('подходящих')}, из них с адресом ${n('с адресом')}, и ещё не ` +
    `писали ${n('ещё не писали')}. Если последнее число ноль — написаны все; если ноль ` +
    'второе — пора добрать контакты.',
  advertisers: (n, funnel) =>
    `Рекламодателей ${n('рекламодателей')}, из них с найденной ссылкой ${n('со ссылкой')}, ` +
    `со свежей ценой донора ${n('цена донора свежая')}, с адресом ${n('с адресом')}, и ещё не ` +
    `писали ${n('ещё не писали')}. ${stopOf(funnel, ADVERTISER_STOPS) ?? ''}`,
  niche: (n, funnel) =>
    `Бизнесов ниши ${n('бизнесов ниши')}, ждут решения ${n('ждут решения')}, решено «пишем» ` +
    `${n('решено «пишем»')}, из них с адресом ${n('из них с адресом')}, и ещё не писали ` +
    `${n('ещё не писали')}. ${stopOf(funnel, NICHE_STOPS) ?? ''}`,
};

/** Почему очередь пуста — где кончились адресаты, по воронке сервера. */
export function emptyQueueText(funnel: Funnel, target: LetterTarget): string {
  const n = (step: string) => funnel[step] ?? 0;
  return [EMPTY[target](n, funnel).trim(), earlierLetters(funnel, target)]
    .filter((said) => said !== null && said !== '')
    .join(' ');
}

/** Первая ступень воронки — из скольких всего. */
const POOL: Record<LetterTarget, string> = {
  donors: 'подходящих',
  advertisers: 'рекламодателей',
  niche: 'бизнесов ниши',
};

/** Подпись под «Ещё не писали»: из скольких всего. */
export function poolHint(funnel: Funnel, target: LetterTarget): string {
  return `${POOL[target]} ${funnel[POOL[target]] ?? 0}`;
}
