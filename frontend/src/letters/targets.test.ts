/**
 * Воронка доноров на «Письмах»: «кому не пишем» по ТЗ — ступенью и строкой.
 *
 * Сверка ТЗ 11.10.2026: принятые раньше крупные сайты (DR > 80) и СМИ писем не
 * получают. Сервер шлёт ступень «вне «кому не пишем»», только когда она кого-то
 * вычеркнула (`letters/funnel.py`), — экран рисует её на своём месте и называет
 * причину строкой рядом.
 */

import { describe, expect, it } from 'vitest';

import { addressHint, buildHint, funnelNotes, funnelSteps, stopOf } from './targets';

const SKIPPED = {
  подходящих: 12,
  принятых: 5,
  'вне «кому не пишем»': 3,
  'с адресом': 3,
  'вне стоп-листа': 3,
  'ещё не писали': 2,
};

describe('«кому не пишем» в воронке доноров', () => {
  it('ступень стоит между принятыми и адресом', () => {
    expect(funnelSteps(SKIPPED, 'donors').map((one) => one.step)).toEqual([
      'подходящих',
      'принятых',
      'вне «кому не пишем»',
      'с адресом',
      'вне стоп-листа',
      'ещё не писали',
    ]);
  });

  it('сколько вычеркнуто и почему — строкой', () => {
    expect(funnelNotes(SKIPPED, 'donors')).toEqual([
      'Не пишем 2 принятым донорам: крупные сайты, гос. и учебные сайты, платформы, соцсети, СМИ и справочники.',
    ]);
  });

  it('все принятые в списке — совет называет ТЗ', () => {
    const none = { ...SKIPPED, 'вне «кому не пишем»': 0, 'с адресом': 0 };

    const stop = stopOf(funnelSteps(none, 'donors'));

    expect(stop?.step).toBe('вне «кому не пишем»');
    expect(stop?.advice).toContain('из «кому не пишем»');
  });

  it('ступени нет — нет ни её, ни строки', () => {
    const plain = { подходящих: 4, принятых: 3, 'с адресом': 2 };

    expect(funnelSteps(plain, 'donors').map((one) => one.step)).toEqual([
      'подходящих',
      'принятых',
      'с адресом',
    ]);
    expect(funnelNotes(plain, 'donors')).toEqual([]);
  });
});

describe('адрес есть не у всех решённых — бизнесы ниши (тест-группа 29.10.2026)', () => {
  const funnel = {
    'решено «пишем»': 180,
    'из них с адресом': 8,
    'ждут поиска адреса': 170,
    'адреса не нашлось': 2,
  };

  it('шапка и подсказка у сборки называют, кому соберутся письма и что с остальными', () => {
    expect(addressHint(funnel, 'niche')).toBe(' · адрес есть у 8 из 180 решённых');
    expect(buildHint(funnel, 'niche')).toBe(
      'Письма соберутся тем, у кого есть адрес: 8 из 180 решённых «пишем». ' +
        'Ещё 170 ждут поиска адреса — когда он кончится, соберите очередь ещё раз. ' +
        'У 2 адреса не нашлось — у кого на сайте есть форма, тот в очереди «Формы».',
    );
  });

  it('адрес у всех решённых или вкладка не ниши — молчат', () => {
    const everyone = { 'решено «пишем»': 3, 'из них с адресом': 3 };
    expect(addressHint(everyone, 'niche')).toBe('');
    expect(buildHint(everyone, 'niche')).toBeNull();
    expect(addressHint(funnel, 'advertisers')).toBe('');
    expect(buildHint(funnel, 'donors')).toBeNull();
  });
});
