/**
 * Воронка доноров на «Письмах»: «кому не пишем» по ТЗ — ступенью и строкой.
 *
 * Сверка ТЗ 11.10.2026: принятые раньше крупные сайты (DR > 80) и СМИ писем не
 * получают. Сервер шлёт ступень «вне «кому не пишем»», только когда она кого-то
 * вычеркнула (`letters/funnel.py`), — экран рисует её на своём месте и называет
 * причину строкой рядом.
 */

import { describe, expect, it } from 'vitest';

import { funnelNotes, funnelSteps, stopOf } from './targets';

const SKIPPED = {
  подходящих: 12,
  принятых: 5,
  'вне «кому не пишем»': 3,
  'с адресом': 3,
  'вне стоп-листа': 3,
  'ещё не писали': 2,
};

describe('«кому не пишем» в воронке доноров', () => {
  it('ступень стоит между принятыми и адресом', () => {
    expect(funnelSteps(SKIPPED, 'donors').map((one) => one.step)).toEqual([
      'подходящих',
      'принятых',
      'вне «кому не пишем»',
      'с адресом',
      'вне стоп-листа',
      'ещё не писали',
    ]);
  });

  it('сколько вычеркнуто и почему — строкой', () => {
    expect(funnelNotes(SKIPPED, 'donors')).toEqual([
      'Не пишем 2 принятым донорам: крупные сайты, гос. и учебные сайты, платформы, соцсети, СМИ и справочники.',
    ]);
  });

  it('все принятые в списке — совет называет ТЗ', () => {
    const none = { ...SKIPPED, 'вне «кому не пишем»': 0, 'с адресом': 0 };

    const stop = stopOf(funnelSteps(none, 'donors'));

    expect(stop?.step).toBe('вне «кому не пишем»');
    expect(stop?.advice).toContain('из «кому не пишем»');
  });

  it('ступени нет — нет ни её, ни строки', () => {
    const plain = { подходящих: 4, принятых: 3, 'с адресом': 2 };

    expect(funnelSteps(plain, 'donors').map((one) => one.step)).toEqual([
      'подходящих',
      'принятых',
      'с адресом',
    ]);
    expect(funnelNotes(plain, 'donors')).toEqual([]);
  });
});
