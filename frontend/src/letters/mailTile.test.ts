/**
 * Плитка «Почта» словами: до 07.10.2026 в ней стоял код транспорта
 * («sendgrid»), а пояснение «подключается на рабочем сервере» обещало то,
 * чего экран знать не может.
 */

import { describe, expect, it } from 'vitest';

import { mailLine, mailTile } from './mailTile';

describe('плитка «Почта»', () => {
  it('настоящая — имя платформы и «письма уходят»', () => {
    expect(mailTile({ name: 'sendgrid', real: true, problem: null })).toEqual({
      value: 'SendGrid',
      hint: 'письма уходят',
    });
  });

  it('незнакомая настоящая — словами, а не кодом', () => {
    expect(mailTile({ name: 'mailer-x', real: true, problem: null }).value).toBe('подключена');
  });

  it('нулевой транспорт — проверочная почта', () => {
    expect(mailTile({ name: 'null', real: false, problem: null })).toEqual({
      value: 'не подключена',
      hint: 'проверочная почта, письма не уходят',
    });
  });

  it('не собравшаяся — не проверочная: причина в плашке ниже', () => {
    expect(mailTile({ name: '—', real: false, problem: 'ключа нет' })).toEqual({
      value: 'не подключена',
      hint: 'письма не уходят',
    });
  });
});

/** Та же почта фразой на главной: до 08.10.2026 там стояло «почта подключается
 *  на рабочем сервере» — обещание, ложное на рабочем сервере с выключенной почтой. */
describe('почта фразой на главной', () => {
  it('проверочная — так и названа, и что с письмами', () => {
    expect(mailLine({ name: 'null', real: false, problem: null })).toBe(
      'Проверочная почта: письма собираются и правятся, но наружу не уходят.',
    );
  });

  it('не собравшаяся — не проверочная, как у плитки', () => {
    expect(mailLine({ name: '—', real: false, problem: 'ключа нет' })).toBe(
      'Почта не подключилась: письма собираются и правятся, но наружу не уходят.',
    );
  });

  it('настоящая — фразы нет: значок «почта подключена» говорит всё', () => {
    expect(mailLine({ name: 'sendgrid', real: true, problem: null })).toBeNull();
  });
});
