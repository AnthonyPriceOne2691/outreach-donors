/**
 * Плитка «Почта» на экране писем — словами (решение владельца 07.10.2026).
 *
 * Сервер называет транспорт кодом (`letters/transport_factory.py`), и до
 * 07.10 в плитке так и стояло «sendgrid». По коду транспорт ищут в журнале;
 * человеку нужно имя платформы и одно — уходят ли письма.
 */

import type { LetterTransport } from '../api/types';

/** Платформы отправки по имени. Незнакомая настоящая — общими словами,
 *  а не кодом: сервер завёл новую, а экран о ней ещё не знает. */
const PLATFORMS: Record<string, string> = { sendgrid: 'SendGrid' };

export interface MailTile {
  value: string;
  hint: string;
}

export function mailTile(transport: LetterTransport): MailTile {
  if (transport.real) {
    return { value: PLATFORMS[transport.name] ?? 'подключена', hint: 'письма уходят' };
  }
  // Настоящая почта выбрана, но не собралась — это не проверочная: причина
  // стоит плашкой «Почта не подключилась» ниже, и подпись ей не перечит.
  if (transport.problem !== null) return { value: 'не подключена', hint: 'письма не уходят' };
  return { value: 'не подключена', hint: 'проверочная почта, письма не уходят' };
}

/** Та же почта одной фразой — на главной, под значком «почта не подключена»;
 *  `null` — почта настоящая, сказать нечего. Факт, а не обещание: до 08.10.2026
 *  там стояло «почта подключается на рабочем сервере», а на рабочем сервере
 *  с выключенной почтой это неправда. Не собравшаяся настоящая — не
 *  проверочная: её причина на экране писем, плашкой «Почта не подключилась». */
export function mailLine(transport: LetterTransport): string | null {
  if (transport.real) return null;
  const which = transport.problem === null ? 'Проверочная почта' : 'Почта не подключилась';
  return `${which}: письма собираются и правятся, но наружу не уходят.`;
}

/** Та же почта в предпросмотре письма, над «Отправить»: фраза `mailLine` и что
 *  станет с этим письмом по нажатию; `null` — почта настоящая. До 08.10.2026 там
 *  стояло обещание «Отправка заработает после подключения на рабочем сервере».
 *  Проверочная почта письмо примет и пометит отправленным; не собравшаяся
 *  настоящая откажет, и письмо останется в очереди — «пометит» о ней было бы
 *  неправдой. */
export function mailSendNote(transport: LetterTransport): string | null {
  const line = mailLine(transport);
  if (line === null || transport.problem !== null) return line;
  return `${line} «Отправить» пометит письмо отправленным, но адресат его не получит.`;
}
