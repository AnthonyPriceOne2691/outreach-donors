/**
 * Анкор найденной ссылки в колонке «Ссылка» — не длиннее трёх строк.
 *
 * Замечание 06.10.2026: анкор-адрес («https://…/promotions/…?utm_source=…»)
 * рвался посреди слов на восемь строк, и строка таблицы вырастала вдвое
 * против соседних. Теперь адрес переносится по швам (`Seams`) — после «/»,
 * перед «.», «?» и «&», — и в своей колонке: посреди части строка рвётся,
 * только если часть шире колонки (`cellName`), таблицу он не раздвигает.
 * Дальше трёх строк — многоточие: «страница», три строки анкора и дата
 * статьи стоят вровень с колонкой «За что». Целиком анкор — в подсказке
 * по наведению и на самой странице донора: ссылка на неё — строкой выше.
 *
 * Подпись держится за начало анкора неразрывным пробелом: «анкор:» одна
 * на своей строке читалась отдельным пунктом, а не подписью к адресу.
 */

import { Text } from '@mantine/core';

import { Seams } from '../components/Seams';

/** Строк анкора в ячейке. */
const ANCHOR_LINES = 3;

export function LinkAnchor({ anchor }: { anchor: string }) {
  return (
    <Text size="xs" c="dimmed" className="cellName" lineClamp={ANCHOR_LINES} title={anchor}>
      анкор:{' '}
      <Seams text={anchor} />
    </Text>
  );
}
