/**
 * Уведомление — отсюда, а не напрямую из Mantine (аудит экранов 09.10.2026, второй круг).
 *
 * **Отказ не исчезает сам.** Уведомление Mantine закрывается через 4 секунды. Для
 * «готово» это верно, для отказа — нет: отвлёкся на соседнее окно — и не узнал, что
 * письмо не ушло или цена не записалась. NN/g описывает ровно это: человек пять
 * минут ждал загрузку, не заметив ошибки, исчезнувшей через пять секунд; Carbon
 * разрешает автоскрытие только тому, что не требует действия.
 *
 * **Правило одно, а не у каждого вызова**: красных уведомлений полсотни на двух
 * десятках экранов, и новое, забывшее про `autoClose`, исчезало бы снова. Отказ
 * закрывает человек; явный `autoClose` у вызова сильнее правила.
 */

import { notifications } from '@mantine/notifications';
import type { NotificationData } from '@mantine/notifications';

/** Показать уведомление; красное — отказ — без явного срока остаётся на экране. */
export function notify(data: NotificationData): string {
  const refusal = data.color === 'red' && data.autoClose === undefined;
  return notifications.show(refusal ? { ...data, autoClose: false } : data);
}
