/**
 * Размер файла на экране — через одну функцию, как деньги и даты.
 * Неизвестный размер словами: «0 байт» читалось бы как пустой файл.
 */

import { describe, expect, it } from 'vitest';

import { formatBytes } from './format';

describe('размер файла', () => {
  it.each([
    [0, '0 байт'],
    [1, '1 байт'],
    [3, '3 байта'],
    [812, '812 байт'],
    [1024, '1 КБ'],
    [12_697, '12,4 КБ'],
    [1_572_864, '1,5 МБ'],
    [10 * 1024 * 1024, '10 МБ'],
  ])('%d → %s', (size, expected) => {
    expect(formatBytes(size)).toBe(expected);
  });

  it('неизвестный размер — словами', () => {
    expect(formatBytes(null)).toBe('размер неизвестен');
  });
});
