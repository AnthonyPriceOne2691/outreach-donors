/**
 * Где лежит пропуск между перезагрузками страницы.
 *
 * Выбран `localStorage`, а не память вкладки: пропуск живёт сутки, и
 * человек, обновивший страницу, не должен вводить пароль заново.
 * Плата известна — сценарий с чужим скриптом на странице достаёт пропуск
 * оттуда; она принята потому, что альтернатива (пропуск только в памяти)
 * при сроке в сутки означает вход при каждом обновлении, а вводимый
 * по десять раз в день пароль становится коротким.
 *
 * Ключ с названием сервиса: на одном домене может оказаться соседнее
 * приложение, и общий ключ вроде `token` они бы делили.
 */

const KEY = 'outreach_donors_token';

/** Кому сообщить, что пропуск больше не действует. Слушатель один —
 *  это состояние сессии; список слушателей тут был бы обещанием, что
 *  их может быть несколько, а их не бывает. */
let onLost: (() => void) | null = null;

export function watchTokenLoss(listener: () => void): () => void {
  onLost = listener;
  return () => {
    onLost = null;
  };
}

export function readToken(): string | null {
  try {
    return localStorage.getItem(KEY);
  } catch {
    // Хранилище может быть недоступно (приватный режим, запрет сайту).
    // Это не повод падать: человек просто войдёт заново.
    return null;
  }
}

export function saveToken(token: string): void {
  try {
    localStorage.setItem(KEY, token);
  } catch {
    /* см. выше */
  }
}

export function clearToken(): void {
  try {
    localStorage.removeItem(KEY);
  } catch {
    /* см. выше */
  }
  // Пропуск мог быть выброшен не выходом, а отказом сервера на любом
  // запросе. Сессия обязана узнать об этом сама, иначе экран остаётся
  // нарисованным для человека, которого уже не пускают.
  onLost?.();
}
