# Настройки кронов хоста — из файлов рядом с кодом, а не из строки крона.
# Подключается из backup.sh, offsite.sh, alert.sh и healthwatch.sh
# (`. scripts/ops_env.sh && ops_env_load "$ROOT"`); сам не запускается.
#
# Крон и ручной запуск (бэкап перед выкаткой) должны выгружать копию
# и слать тревоги одинаково. Настройка, записанная в строку крона, у ручного
# запуска отсутствует — и копия, снятая перед выкаткой, молча осталась бы
# на машине. Поэтому скрипты читают настройки сами.
#
# Где что лежит на сервере (deploy/README.md, «Копия вне машины и тревоги»):
#   .env      — ALERT_TELEGRAM_*: их читают и контейнеры (тревога
#               об остановленном прогоне), и кроны; одно значение на двоих,
#               а не две копии токена, которые однажды разойдутся;
#   .env.ops  — BACKUP_S3_*: ключи хранилища нужны только хосту. В `.env`
#               им не место: компоуз отдаёт `.env` в контейнеры целиком,
#               и ключ, которым можно стереть копии, оказался бы в сервере,
#               смотрящем в интернет.
#
# Читаются только свои имена — ALERT_*, BACKUP_*, HEALTHWATCH_*: в `.env`
# лежат пароль базы и ключи провайдеров, скрипту хоста они не нужны.
# Строки не исполняются: `source .env` выполнил бы `$(…)` в любом значении,
# а файл правят руками. Формат — как у docker compose: KEY=value, значение
# в кавычках или без, `#` в начале строки и « #» после значения без
# кавычек — комментарий.
#
# **Окружение важнее файла:** `KEEP=10 scripts/backup.sh` перед выкаткой
# и `BACKUP_UPLOAD= scripts/backup.sh` (выгрузку выключить на один запуск)
# обязаны побеждать. Из двух файлов побеждает первый: .env.ops, затем .env.

# ops_env_load КАТАЛОГ — прочитать КАТАЛОГ/.env.ops и КАТАЛОГ/.env.
# OPS_ENV_DIR заменяет каталог: так тесты не читают `.env` разработчика.
ops_env_load() {
  local dir="${OPS_ENV_DIR:-$1}" file line key value
  for file in "$dir/.env.ops" "$dir/.env"; do
    [ -r "$file" ] || continue
    while IFS= read -r line || [ -n "$line" ]; do
      line="${line%$'\r'}"
      line="${line#export }"
      case "$line" in
        ALERT_*=* | BACKUP_*=* | HEALTHWATCH_*=*) ;;
        *) continue ;;
      esac
      key="${line%%=*}"
      case "$key" in *[!A-Z0-9_]*) continue ;; esac
      value="${line#*=}"
      case "$value" in
        \"*\") value="${value#\"}" && value="${value%\"}" ;;
        \'*\') value="${value#\'}" && value="${value%\'}" ;;
        *)
          value="${value%% #*}"
          value="${value%"${value##*[![:space:]]}"}"
          ;;
      esac
      [ -n "${!key+x}" ] || export "$key=$value"
    done <"$file"
  done
}
