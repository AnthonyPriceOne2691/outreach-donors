#!/usr/bin/env python3
"""Суждение о ПЛОЩАДИ гейта: сколько он посмотрел против того, что в дереве.

Часть `contour_doctor.py` (`cqg@1.98`). Отделена от `doctor_areas.py` не по вкусу,
а по замеру: после закрытия долга по функциям тот стал **403 строки** — рекордом
контура, — и долг просто переехал с функций на файлы. Здесь живёт всё, что решает
«просмотрено N из M и что это значит»; там осталось «прогнать гейт и прочитать
его число».

Граница проверяема: этот файл не запускает гейты и не читает конфиги, он только
СУДИТ уже полученные числа.
"""

from __future__ import annotations

import fnmatch
import re
from pathlib import Path

from doctor_core import AUTO, DEAD, SKIP_WORDS, SUCCESS_WORDS, WEAK


def _covers(token: str, path: str) -> bool:
    """Покрывает ли токен маски этот путь.

    Три формы, все встречаются в payload'е: `*.py` (расширение где угодно),
    `dir/**` (поддерево) и `dir/**/*.py` (то и другое). Голый `fnmatch` не
    годится: `*.py` в нём не совпадает с `pkg/mod.py`, а `**` он не знает вовсе.
    """
    # ⚠ Маска, укоренённая в КОРНЕ репозитория, приходит как `./**` или
    # `./**/*.py`: `LINT_PY_SRC=.` — законная настройка (таблица «Применимость»),
    # а `git ls-files` отдаёт пути БЕЗ `./`. Прежняя форма сравнивала префикс
    # буквально, поэтому корневая маска не покрывала НИ ОДНОГО файла, и доктор
    # объявлял три гейта `DEAD` — вердикт, который сам же определяет как «только
    # это ложь», — на проекте, где гейт в тот же момент печатал «просмотрено 132
    # файл(ов)». Нашло ТРЕТЬЕ полевое развёртывание; раскладка самого канона
    # (`backend/features`) работала, и потому дефекта не видел никто: везение
    # раскладки, а не защита.
    if token.startswith("./"):
        token = token[2:]
    if token in ("**", "**/*"):
        return True
    if token.startswith("**/"):
        return fnmatch.fnmatch(path.rsplit("/", 1)[-1], token[3:])
    if token.endswith("/**"):
        return path.startswith(token[:-2])
    if "/**/" in token:
        head, tail = token.split("/**/", 1)
        return path.startswith(head + "/") and fnmatch.fnmatch(
            path.rsplit("/", 1)[-1], tail)
    if "/" in token:
        return fnmatch.fnmatch(path, token)
    return fnmatch.fnmatch(path.rsplit("/", 1)[-1], token)


def _gate_roots(env: dict) -> list[str]:
    """Корни гейта (`LINT_*_SRC` / `_DIR`) — нормализованные, без «всего репозитория».

    Шов и по данным, и по сложности: наружу цикл отдаёт одно имя — `roots`, а
    одна только нормализация стоила суждению о площади семь ветвлений из
    двадцати пяти.

    `LINT_FE_DIR=.` — штатная запись npm-проекта без каталога frontend, и
    означает она ВЕСЬ репозиторий. Первая редакция считала её корнем с именем
    «.», под который не подходит ни один путь из `git ls-files`: область
    выходила пустой, сверять становилось не с чем, и проверка молчала ровно
    там, где стек смешанный. Поймано полевым прогоном на portfolio-site, а не
    чтением.
    """
    roots = []
    for k, v in env.items():
        if not (k.endswith("_SRC") or k.endswith("_DIR")):
            continue
        r = v.strip().rstrip("/")
        r = r[2:] if r.startswith("./") else r
        if r and r != ".":
            roots.append(r)
    return roots


def _area_of(files: list[str], env: dict, files_re) -> list[str]:
    """Дерево под корнями гейта и его `files:` — знаменатель сверки (`cqg@1.80`).

    Шов по данным: выборка отдаёт наружу одно имя — `area`; `roots` за границу
    не переходит, его читает только сама выборка.
    """
    roots = _gate_roots(env)
    return [f for f in files
            if (not roots or any(f == r or f.startswith(r + "/") for r in roots))
            and (files_re is None or files_re.search(f))]


class AreaVerdicts:
    """Вердикты о площади: методы примешиваются к `Doctor` (`cqg@1.98`)."""

    def _judge_area(self, point: str, n: int, unit: str, files: list[str],
                    env: dict, *, multi_rule: bool, files_re, mask: list[str]) -> None:
        """Число просмотренного сверяется с ДЕРЕВОМ (`cqg@1.80`).

        Единственным порогом был НОЛЬ (`if n: AUTO`), а дыра, из которой родилась
        сама проверка, была ЕДИНИЦЕЙ: `file-length` с дефолтной маской
        `*.py *.ts *.tsx` на Astro-проекте печатал `OK — просмотрено 1 файл(ов)`
        при четырёх файлах кода — `.ts` виден, `.astro` невидим. То есть
        предохранитель, построенный по находке, саму находку бы не поймал: полную
        слепоту он ловит, а на смешанном стеке опасна ровно ЧАСТИЧНАЯ, и она
        читается как успех. Обе половины наблюдались в одном отчёте, это замер, а
        не гипотеза.

        **Знаменатель — дерево под КОРНЯМИ гейта, но не под его маской
        расширений.** Корень (`LINT_*_SRC`/`_DIR` из `entry:`) отвечает «где», и
        сузить его — законное решение проекта. Маска отвечает «на каком языке», и
        сверять её с самой собой значило бы объявить зелёным ровно тот случай,
        ради которого проверка написана.

        Вердикт частичной области — `WEAK`, не `DEAD`, и это не мягкость.
        Приписать гейту весь язык доктор не может: единственное, что он видит, —
        два числа, а какие именно файлы гейт смотрел, знает только сам гейт.
        `WEAK` печатает числа и состав дерева, то есть отдаёт человеку ровно ту
        улику, по которой находка №1 и была найдена глазами.
        """
        area = _area_of(files, env, files_re)
        # Сравнивать не с чем — два разных случая, и оба остаются прежним AUTO:
        # единица не файлы (манифесты, модули) либо в области нет ни одного
        # известного доктору исходника.
        if not unit.startswith("файл"):
            self.add(AUTO, point,
                     f"просмотрено {n} — сверить с деревом нечем (единица: {unit})")
            return
        if not area:
            self.add(AUTO, point, f"просмотрено {n} файл(ов)")
            return
        if self._blind_by_mask(point, area, mask):
            return
        if n >= len(area):
            self.add(AUTO, point, f"просмотрено {n} из {len(area)} файл(ов) области"
                                  + (", маска покрывает область" if mask else ""))
            return
        hist: dict[str, int] = {}
        for f in area:
            ext = "." + f.rsplit(".", 1)[-1]
            hist[ext] = hist.get(ext, 0) + 1
        top = ", ".join(f"{e} ×{c}" for e, c in
                        sorted(hist.items(), key=lambda kv: -kv[1])[:4])
        if multi_rule:
            self.add(AUTO, point, f"просмотрено {n} из {len(area)} — у правила свой "
                                  f"FILTER, частичная область законна ({top})")
            return
        self.add(WEAK, point,
                 f"просмотрено {n} из {len(area)} файл(ов) области: {len(area) - n} "
                 f"мимо гейта (в дереве {top}) — так выглядела находка №1, где "
                 "«просмотрено 1» при четырёх файлах читалось как успех. Сверь маску (§6)")

    def _judge_blindness_together(self) -> None:
        """Слепота судится ОБЪЕДИНЕНИЕМ масок, а не маской одного гейта.

        Файл, которого не покрывает ни одна маска, не судит НИКТО — вот это ложь
        объявленной роли, и она остаётся `DEAD`. Файл, покрытый соседним гейтом,
        снимается с этого: у смешанного стека роли делят по языкам, и требовать
        от python-гейта Swift значит требовать невыполнимого, а невыполнимые
        правила снимают вместе с ратчетом (§4.3b).

        ⚠ Что этой правкой ТЕРЯЕТСЯ, и это названо, а не замолчано: случай
        «файл формально под маской, но гейт его не судит своим FILTER» перестаёт
        ловиться здесь. Он остаётся за `WEAK` по числам («просмотрено N из M»),
        то есть улика становится слабее — числа вместо имён.
        """
        pending = getattr(self, "_blind_pending", [])
        if not pending:
            return
        # ⚠ Объединение берётся из масок ЖИВЫХ гейтов, а не из масок самих
        # ослепших. Первая редакция считала `covered` по `pending` — то есть по
        # тем же гейтам, у которых слепота и нашлась: гейт, покрывающий свою
        # область целиком, в список не попадал вовсе, и оправдание работало
        # только когда два гейта слепы ДРУГ К ДРУГУ. На `lash-try-on` это
        # совпало (python и swift слепы взаимно) и выглядело верным.
        covered = self._live_masks
        for point, blind, mask in pending:
            orphan = [f for f in blind
                      if not any(_covers(tok, f) for tok in covered)]
            if not orphan:
                self.add(WEAK, point,
                         f"маска гейта не покрывает {len(blind)} файл(ов) "
                         f"области, но их судят соседние гейты (маска — "
                         f"«{' '.join(mask)}»): роли делятся по языкам")
                continue
            self.add(DEAD, point,
                     f"маска гейта не покрывает {len(orphan)} файл(ов) области: "
                     f"{', '.join(orphan[:3])}{' …' if len(orphan) > 3 else ''}. "
                     f"Маска — «{' '.join(mask)}»; этих файлов не видит НИ ОДИН "
                     "подключённый гейт, а роль объявлена закрытой (§6)")

    def _blind_by_mask(self, point: str, area: list[str], mask: list[str]) -> bool:
        """Файлы области мимо маски гейта → DEAD. Возвращает: судил ли этим.

        Шов по данным: `blind` считается в ветке и в ней же читается, наружу не
        выходит — уходит только решение «вердикт вынесен, дальше не смотрим».
        Охрана `if mask` — часть блока, поэтому восстановлена ранним возвратом.

        ⚠ Маска, если гейт её НАЗВАЛ, превращает подозрение в счёт (`cqg@1.88`).
        Без неё «просмотрено 1 из 4» одинаково выглядит при узкой маске и при
        законном сужении области — доктор мог только спросить (`WEAK`). Теперь
        он вычитает: файлы области, которых маска не покрывает, гейт не увидит
        НИКОГДА, и это уже не вопрос, а ложь объявленной роли.
        """
        if not mask:
            return False
        blind = [f for f in area if not any(_covers(tok, f) for tok in mask)]
        if not blind:
            return False
        # ⚠ Вердикт ОТЛОЖЕН до конца обхода, и это несущая часть. Судить площадь
        # маской ОДНОГО гейта — значит объявлять лжецом python-гейт за то, что
        # рядом лежит Swift: на смешанном стеке, где языки переплетены в одном
        # каталоге, законного хода не остаётся вовсе (корень сузить нельзя, он
        # общий). Замер: `lash-try-on`, восемь `.swift` в `scripts/` рядом с
        # питоновскими — гейт DEAD по построению.
        #
        # Свойство, ради которого проверка написана, при этом СОХРАНЯЕТСЯ:
        # оправдаться собственной маской по-прежнему нельзя. Сузив её, гейт не
        # спасается — файл переходит в ответственность другого гейта, а если его
        # не покрывает НИ ОДИН, `DEAD` остаётся. Вопрос стал точнее: не «слеп ли
        # этот гейт», а «есть ли код, который не судит никто».
        self._blind_pending.append((point, blind, list(mask)))
        return True

    def _judge_zero(self, point: str, out: str, env: dict, *,
                    multi_rule: bool) -> None:
        """Просмотрено 0 — бедность окружения или ложь объявленной роли.

        Шов по данным: ветка нуля не отдаёт наружу НИ ОДНОГО имени, только
        вердикты; `named` и `missing` живут и умирают внутри неё. Выход из
        цикла превращается в `return` без смены смысла: за веткой в теле
        цикла ничего нет.

        ⚠ Ноль при НАЗВАННОМ пропуске — бедность, а не ложь, и этот случай
        обнажила сама правка 1.80. `check_deps_audit.sh` печатает
        «○ пропущено: npm audit» и `WARNING — просмотрено 0 манифест(ов)»;
        до 1.80 он проваливался в `SKIP` лишь потому, что регулярка не знала
        слова «манифест», а как только число стало читаться, честный пропуск
        стал бы `DEAD` — то есть проверка на ложь обвинила бы гейт за
        бедность окружения (§4.3b). Правило 1.61 сохранено: заявленный успех
        БЬЁТ названный пропуск (гейт может шепнуть «пропущено» в теле и
        напечатать «: OK» в итоге, а читают итог — это форма F10 и она DEAD).
        """
        named = next((w for w in SKIP_WORDS if w in out), None)
        if named and not any(w in out for w in SUCCESS_WORDS):
            self.add(WEAK, point, f"просмотрено 0 — но пропуск НАЗВАН самим "
                                  f"гейтом ({named}): бедность окружения, не ложь")
            return

        # Ноль бывает ДВУХ природ, и путать их нельзя.
        #
        # ① Гейт настроен на НЕСУЩЕСТВУЮЩИЙ путь — это ложь всегда: роль
        #    объявлена закрытой, а смотреть физически некуда.
        # ② У правила свой FILTER (`service-no-web` смотрит только в
        #    `/services/`), и ноль честно значит «предмета здесь нет».
        #
        # Первая редакция звала DEAD в обоих случаях и обвинила
        # `check_grep_gate.sh` на стенде, где каталог был на месте, а у
        # правила просто не было предмета. Ложное срабатывание — дефект
        # проверки (§4.3b), и такой доктор снимают раньше, чем он окупится.
        # Поймано собственным тестом процедуры, а не полем.
        missing = self._missing_roots(env)
        if missing:
            self.add(DEAD, point,
                     "настроен на НЕСУЩЕСТВУЮЩИЙ путь "
                     f"({', '.join(missing)}) — смотреть некуда, а роль "
                     "объявлена закрытой (§6: значения живут в `entry:`)")
        elif multi_rule:
            self.add(WEAK, point,
                     "просмотрено 0 файлов. У правила свой FILTER, поэтому "
                     "ноль может честно значить «предмета нет» — но может и "
                     "«маска шаблонная». Отсюда не различить: сверь §6")
        else:
            self.add(DEAD, point,
                     "подключён и смотрит в ПУСТОТУ: просмотрено 0 файлов. "
                     "Роль объявлена закрытой, а гейт не видит кода — маска "
                     "или путь остались шаблонными (§6: значения в `entry:`)")
