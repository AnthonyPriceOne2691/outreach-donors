def estimate(page):
    """Ключ один и настоящий: смета — бесплатный запрос, она
    спрашивает остаток у провайдера и ничего не покупает."""
    page.get_by_label("Ключевые слова").fill("ремонт квартир")
    page.get_by_role("button", name="Посчитать смету").click()
    # Ждём именно того, ради чего смета и считается: пока кнопка
    # запуска не ожила, мерить у неё нечего.
    expect(page.get_by_role("button", name="Запустить")).to_be_enabled()
    # Второй режим поля ключей включается ПОСЛЕ сметы: он её сбрасывает,
    # и включённый до — снова выключает главную кнопку, а у выключенной
    # меряется серое на сером.
    # Кликается ПОДПИСЬ, а не роль: у Mantine сам радио-вход спрятан,
    # и playwright по роли ждёт видимости до таймаута.
    page.locator(".mantine-SegmentedControl-label", has_text="Собрать моделью").click()
    expect(page.get_by_role("button", name="Собрать")).to_be_visible()
    page.wait_for_timeout(400)


def open_letter_draft(page):
    """Раскрыть правку текста письма и поправить зону.

    Правка оживляет «Вернуть исходный текст» и переводит значок
    в «поправлен» — мерить надо то состояние, в котором на них смотрят.
    """
    page.get_by_role("button", name="Текст первого письма").click()
    # Приветствие — «Hi,», три знака в широкой рамке: вырезка почти целиком
    # фон, и в тёмной теме замер давал 1,9 : 1 полю, у которого те же стили,
    # что у «Вопросов» с 5,5 : 1. Меряется поле с фразой, а не с тремя знаками.
    page.get_by_label("Приветствие").fill("Hello there, and thank you for reading this,")
    field = page.get_by_label("Условия")
    field.fill(field.input_value() + " Thank you.")
    expect(page.get_by_role("button", name="Вернуть исходный текст")).to_be_enabled()
    page.wait_for_timeout(300)


